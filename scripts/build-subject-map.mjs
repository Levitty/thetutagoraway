// ============================================================================
// GENERIC CURRICULUM-MAP BUILDER: any subject, any grade. Reads the design file HOREB owns,
//   curriculum/<dir>/g<N>.json     (official outcomes word for word; skills, prerequisites and misconceptions
//                                    are proposed or draft until a teacher reviews them)
// and writes the in-app map and the two heavy files the checks and review pack read:
//   src/ai-tutor/content/curriculumMap.<subject>.g<N>.js          light: SUBSTRANDS, OUTCOMES, SKILLS, MIS_FEEDBACK
//   engine/data/curriculum/<subject>.g<N>.misconceptions.json     the misconception library
//   engine/data/curriculum/<subject>.g<N>.detail.json             outcome texts, mastery rules, question forms
//
//   node scripts/build-subject-map.mjs <subject> <grade> [--dir <curriculum dir>] [--title "Science and Technology"] [--source <json path>]
//   e.g.  node scripts/build-subject-map.mjs kiswahili 5 --dir kiswahili --title Kiswahili
//
// The curriculum JSON must already carry skills and misconceptions under each sub-strand
// (sub_strands[].skills[] with code, name, outcomes[], prerequisites[], question_forms, mastery;
//  sub_strands[].misconceptions[] with code, skill, error, example, cause, reveals, help, feedback, source, status).
// If the subject authors them elsewhere first (as English does: scripts/build-english-g5.mjs merges
// scripts/data/english-g5-skills.mjs into the JSON), run that merge first, then this.
// The generic exports are SKILLS, SUBSTRANDS, OUTCOMES, MIS_FEEDBACK, MAP_SOURCE; Science Grade 5 also keeps the older
// names (SKILLS_SCI_G5 ...) because families and tests were written against them.
// A family carries `cskill` (a key of SKILLS) and `outcome` (its official outcome code).
// ============================================================================
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const flag = (n) => (args.includes(n) ? args[args.indexOf(n) + 1] : null);
const [subject, gradeArg] = args.filter((a, i) => !a.startsWith('--') && !(i > 0 && args[i - 1].startsWith('--')));
const grade = Number(gradeArg);
if (!subject || !/^[a-z][a-z0-9_]*$/.test(subject) || !Number.isInteger(grade)) {
  console.error('usage: node scripts/build-subject-map.mjs <subject> <grade> [--dir <curriculum dir>] [--title <name>] [--source <json>]');
  process.exit(1);
}
const dir = flag('--dir') || subject;
const title = flag('--title') || subject;
const srcRel = `curriculum/${dir}/g${grade}.json`;
const src = flag('--source') || resolve(root, srcRel);
const design = JSON.parse(readFileSync(src, 'utf8'));
const out = { source: srcRel, status: design.status, subs: {}, outcomes: {}, skills: {} };
const mis = {}, detail = { outcomes: {}, skills: {} }, fb = {};
const GRADE_SKILLS = new Set(design.sub_strands.flatMap(x => (x.skills || []).map(k => k.code)));
if (!GRADE_SKILLS.size) { console.error(`${srcRel} has no skills yet: author them first (see the header of this script)`); process.exit(1); }
for (const s of design.sub_strands) {
  out.subs[s.code] = { name: s.sub_strand, strand: s.strand, outcomes: s.outcomes.map(o => o.code) };
  for (const o of s.outcomes) { out.outcomes[o.code] = { letter: o.letter, sub: s.code }; detail.outcomes[o.code] = o.text; }
  for (const k of s.skills || []) {
    out.skills[k.code] = { name: k.name, sub: s.code, outcome: k.outcomes[0], outcomes: k.outcomes, pre: [...new Set((k.prerequisites || []).map(r => r.requires).filter(c => GRADE_SKILLS.has(c)))], mis: [] };
    detail.skills[k.code] = { forms: k.question_forms, mastery: k.mastery };
  }
  for (const m of s.misconceptions || []) {
    const short = m.code.slice(m.skill.length + 1);
    if (fb[short]) throw new Error(`duplicate misconception code ${short}`);
    out.skills[m.skill].mis.push(short);
    mis[m.code] = { skill: m.skill, error: m.error, example: m.example, cause: m.cause, reveals: m.reveals, help: m.help, feedback: m.feedback, source: m.source, status: m.status };
    fb[short] = m.feedback;
  }
}
// Names the first families and tests used for Science Grade 5.
const LEGACY = { 'science.5': { SKILLS: 'SKILLS_SCI_G5', SUBSTRANDS: 'SUBSTRANDS_SCI_G5', OUTCOMES: 'OUTCOMES_SCI_G5' } }[`${subject}.${grade}`];
const J = (v) => JSON.stringify(v, null, 1);
const header = `// GENERATED by scripts/build-subject-map.mjs from ${srcRel} (${title}, Grade ${grade}). Do not edit by hand.
// Outcomes are official (word for word). Skills are proposed, awaiting teacher review.
// A family carries \`cskill\` (a key of SKILLS), \`outcome\` (its official outcome) and \`skill\` (the same as cskill:
// these skills are not in the practice engine's Maths graph). MIS_FEEDBACK maps a short misconception code to the line a child reads.
`;
const exp = (name, value) => `export const ${name} = ${value};\n`;
let js = header + exp('MAP_SOURCE', JSON.stringify({ source: out.source, status: out.status })) + exp('SUBSTRANDS', J(out.subs)) + exp('OUTCOMES', J(out.outcomes)) + exp('SKILLS', J(out.skills)) + exp('MIS_FEEDBACK', J(fb));
if (LEGACY) js += `// Older names, kept for the families and tests written against them.\n` + Object.entries(LEGACY).map(([k, v]) => `export const ${v} = ${k};\n`).join('') + `export const SCI_MAP_SOURCE = MAP_SOURCE;\n`;
mkdirSync(resolve(root, 'engine/data/curriculum'), { recursive: true });
writeFileSync(resolve(root, `src/ai-tutor/content/curriculumMap.${subject}.g${grade}.js`), js);
writeFileSync(resolve(root, `engine/data/curriculum/${subject}.g${grade}.misconceptions.json`), J(mis) + '\n');
writeFileSync(resolve(root, `engine/data/curriculum/${subject}.g${grade}.detail.json`), J(detail) + '\n');
console.log(`${subject} g${grade} map: ${Object.keys(out.subs).length} sub-strands, ${Object.keys(out.outcomes).length} outcomes, ${Object.keys(out.skills).length} skills, ${Object.keys(mis).length} misconceptions`);

// ============================================================================
// PRE-TECHNICAL STUDIES, ONE GRADE TO THE GRADE 5 MATHS STANDARD (owner, 18 Nov 2026, Tuta Workspace/HOREB_MAPPING_PLAN.md).
//   node scripts/build-pretechnical-grade.mjs 7     (Grades 7, 8, 9; build them in order, a prerequisite may name a skill of a grade below)
// 1. runs the first-pass merge (scripts/build-pretechnical-g<n>.mjs, data in scripts/data/pretechnical-g<n>-skills.mjs): the skills
//    and misconception codes the question families already use;
// 2. adds the depth layer (scripts/data/pretech-depth/g<n>.mjs) through scripts/lib/subject-depth.mjs (the CRE pass, any subject):
//    new skills for testable outcomes that had none (practical outcomes get a knowledge skill; the making is marked with the KICD
//    rubric), more outcomes, prerequisites (this grade, the Pre-Technical grades below, and Science and Technology, Integrated
//    Science, Mathematics and Social Studies skills of the grades below, written S6:, IS7:, M6:, SS6:), more misconceptions, real
//    causes and repairs for the first-pass ones, a teaching pack entry for every skill;
// 3. writes curriculum/pre_technical/g<n>.json, the teaching pack curriculum/pre_technical/teaching/g<n>/*.json, the in-app map
//    (scripts/build-subject-map.mjs), the skills with no family yet (src/ai-tutor/content/families/pretechnical_g<n>_awaiting.js)
//    and the SQL (supabase/migrations/20261129_pretechnical_g<n>_skills_misconceptions.sql, scripts/lib/curriculum-sql.mjs),
//    copied to ~/Desktop/Tuta Workspace/HOREB_SQL_PreTechnical_G<n>.sql. NOT RUN: the owner runs the SQL.
// Official outcomes, sub-strand text and the KICD rubrics are never touched. Skills 'proposed', misconceptions 'draft', pack draft.
// Safety lines carry SAFETY in their source (scripts/data/pretech-depth/common.mjs) for a teacher to confirm.
// ============================================================================
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync, copyFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { deepenGrade, packFiles } from './lib/subject-depth.mjs';
import { curriculumSql } from './lib/curriculum-sql.mjs';
import { PRETECH_NOT_TESTED, REVIEWER, TC } from './data/pretech-depth/common.mjs';

const ROOT = new URL('..', import.meta.url).pathname;
const GRADE = Number(process.argv[2]);
if (![7, 8, 9].includes(GRADE)) { console.error('usage: node scripts/build-pretechnical-grade.mjs 7|8|9'); process.exit(1); }
const run = (args) => { const r = spawnSync('node', args, { stdio: 'inherit', cwd: ROOT }); if (r.status) process.exit(r.status); };
const J = (p) => { const f = join(ROOT, p); return existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : null; };
const load = (g) => (g >= 7 ? J(`curriculum/pre_technical/g${g}.json`) : null);
const MIS_PREFIX = `M_PT${GRADE}_`;

async function writeAwaiting() {
  const entry = (await import(`../src/ai-tutor/content/subjects/pretechnical_g${GRADE}.js?${Date.now()}`)).default;
  const used = new Set(entry.families.map(f => f.cskill));
  const list = Object.keys(entry.map.skills).filter(c => !used.has(c));
  writeFileSync(join(ROOT, `src/ai-tutor/content/families/pretechnical_g${GRADE}_awaiting.js`),
    `// GENERATED by scripts/build-pretechnical-grade.mjs ${GRADE}. Do not edit by hand.\n` +
    `// The Grade ${GRADE} Pre-Technical Studies skills that have no question family yet (${list.length} of ${Object.keys(entry.map.skills).length}).\n` +
    `// The checks list them for the family writers instead of failing; a skill that gets a family must leave this list (rebuild).\n` +
    `export const AWAITING = ${JSON.stringify(list, null, 1)};\n`);
  console.log(`pretechnical g${GRADE}: ${list.length} skills with no family yet`);
}
if (process.argv.includes('--awaiting')) { await writeAwaiting(); process.exit(0); }

// Skills of other subjects, from the grades below: S4-S6 Science and Technology, IS7-IS8 Integrated Science, M4-M8 Mathematics,
// SS4-SS8 Social Studies. 'S6:FORCE_.LIGHT.LIGHT_MATERIALS' -> SCIE.G6.FORCE_.LIGHT.LIGHT_MATERIALS.
const OTHER = { S: ['science', 'SCIE'], IS: ['integrated_science', 'INTE'], M: ['mathematics', 'MATH'], SS: ['social_studies', 'SOCI'] };
const known = new Map();
function resolveExtra(r) {
  const m = /^(S|IS|M|SS)(\d):(.+)$/.exec(r);
  if (!m) return null;
  const [, key, g, rest] = m, [dir, prefix] = OTHER[key];
  if (Number(g) >= GRADE) throw new Error(`prerequisite ${r}: Grade ${g} is not below Grade ${GRADE}`);
  const id = `${dir}${g}`;
  if (!known.has(id)) { const j = J(`curriculum/${dir}/g${g}.json`); known.set(id, new Set(j ? j.sub_strands.flatMap(s => (s.skills || []).map(k => k.code)) : [])); }
  const code = `${prefix}.G${g}.${rest}`;
  if (!known.get(id).has(code)) throw new Error(`unknown skill ${code}`);
  return [code, 'skill'];
}

// ---- 1. the first pass
run([`scripts/build-pretechnical-g${GRADE}.mjs`]);

// ---- 2. the depth layer
const cur = load(GRADE);
const data = await import(`./data/pretech-depth/g${GRADE}.mjs`);
const taken = new Set();
for (const g of [7, 8, 9]) if (g !== GRADE) for (const s of load(g).sub_strands) for (const m of s.misconceptions || []) taken.add(m.code.slice(m.skill.length + 1));
const SUB = `PRE_.G${GRADE}.`, SKILL = `PRET.G${GRADE}.`;
const { packs, added, newSkills } = deepenGrade(cur, data, {
  label: `Pre-Technical Grade ${GRADE}`, grade: GRADE, subPrefix: SUB, skillPrefix: SKILL, lower: load,
  outcomePrefix: (g) => `PRE_.G${g}.`, misPrefix: MIS_PREFIX, taken, notTested: PRETECH_NOT_TESTED, reviewer: REVIEWER,
  masteryRule: /four of the last five/, source: TC, resolveExtra,
});

// ---- 3. write
const PACK_DIR = join(ROOT, `curriculum/pre_technical/teaching/g${GRADE}/`);
mkdirSync(PACK_DIR, { recursive: true });
const files = packFiles(cur, packs, { subPrefix: SUB, skillPrefix: SKILL, notes: data.NOTES || {},
  status: `draft: written 18 Nov 2026 offline for Grade ${GRADE} Pre-Technical Studies; not yet checked by ${REVIEWER}; safety lines marked SAFETY in the library to confirm first; not loaded by the live tutor` });
for (const [slug, text] of Object.entries(files)) writeFileSync(join(PACK_DIR, slug), text);
for (const f of readdirSync(PACK_DIR)) if (f.endsWith('.json') && !files[f]) unlinkSync(join(PACK_DIR, f));
cur.status = `outcomes from KICD's text, word for word; skills and prerequisites proposed, misconceptions draft, teaching pack draft; first pass 13 Nov 2026, deepened to the Grade 5 Maths standard on 18 Nov 2026 (two prerequisites and four misconceptions per skill; practical outcomes have a knowledge skill and are marked with the rubric); written offline by Claude, awaiting ${REVIEWER}'s review, safety lines first. Rubrics from KICD, untouched.`;
writeFileSync(join(ROOT, `curriculum/pre_technical/g${GRADE}.json`), JSON.stringify(cur, null, 1) + '\n');
console.log(`pretechnical g${GRADE} depth: ${newSkills} new skills, +${added.pre} prerequisites (${added.reasoned || 0} first-pass reasons replaced), +${added.mis} misconceptions, ${added.fix} fixed; now ${cur.totals.skills} skills, ${cur.totals.prerequisites} prerequisites, ${cur.totals.misconceptions} misconceptions, ${Object.keys(files).length} teaching pack files`);

run(['scripts/build-subject-map.mjs', 'pretechnical', String(GRADE), '--dir', 'pre_technical', '--title', 'Pre-Technical Studies']);
run(['scripts/build-pretechnical-grade.mjs', String(GRADE), '--awaiting']);

const MIG = `20261129_pretechnical_g${GRADE}_skills_misconceptions.sql`;
const sql = curriculumSql(cur, {
  title: `Grade ${GRADE} Pre-Technical Studies`, when: 'owner, 18 Nov 2026',
  after: '20261110_curriculum.sql (the five curriculum tables); the Pre-Technical grades in order, 7 to 9 (prerequisites name the grade below and Science, Mathematics and Social Studies skills; there is no foreign key on them, so the order is for the reviewer only)',
  why: `Pre-Technical Studies Grade ${GRADE} had a first-pass map in the repository (curriculum/pre_technical/g${GRADE}.json) that no migration loaded; on 18 Nov 2026 it was brought to the Grade 5 Maths standard (a skill for every testable outcome, two prerequisites and four misconceptions per skill, a teaching pack; safety lines marked for a teacher to confirm).`,
  generator: `scripts/build-pretechnical-grade.mjs ${GRADE}`, source: `curriculum/pre_technical/g${GRADE}.json`,
});
writeFileSync(join(ROOT, 'supabase/migrations', MIG), sql.text);
const WS = join(homedir(), 'Desktop', 'Tuta Workspace');
if (existsSync(WS)) copyFileSync(join(ROOT, 'supabase/migrations', MIG), join(WS, `HOREB_SQL_PreTechnical_G${GRADE}.sql`));
console.log(`SQL: ${MIG} (${sql.skills} skills, ${sql.prerequisites} prerequisites, ${sql.misconceptions} misconceptions)${existsSync(WS) ? `, copied to Tuta Workspace/HOREB_SQL_PreTechnical_G${GRADE}.sql` : ''}`);

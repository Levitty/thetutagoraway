// ============================================================================
// KISWAHILI, ONE GRADE TO THE GRADE 5 MATHS STANDARD (18 Nov 2026, HOREB_MAPPING_PLAN.md). The one command for Grades 4 to 9:
//   node scripts/build-kiswahili-grade.mjs 5
// 1. runs the first-pass merge (scripts/build-kiswahili-g<n>.mjs, its data in scripts/data/kiswahili-g<n>-*.mjs): the skills and
//    misconception codes the families already use;
// 2. adds the depth layer (scripts/data/kiswahili-g<n>/index.mjs, helpers in scripts/data/kiswahili-depth-lib.mjs): new skills for
//    every sub-strand that had none, more outcomes, prerequisites (to this grade and the grades below) and misconceptions for the
//    first-pass skills, and a teaching pack entry for every skill;
// 3. checks the standard: every sub-strand has a skill, every testable outcome a skill (only attitude and habit outcomes are left
//    out), every skill at least 2 prerequisites and 4 misconceptions, every misconception a reveal question and a repair;
// 4. writes curriculum/kiswahili/g<n>.json, the teaching pack curriculum/kiswahili/teaching/g<n>/*.json (rules shared with Maths:
//    scripts/maths-teaching-pack-file.mjs), the in-app map (scripts/build-subject-map.mjs), the list of skills with no family yet
//    (src/ai-tutor/content/families/kiswahili_g<n>_awaiting.js) and the SQL (supabase/migrations/20261125_kiswahili_g<n>_...sql,
//    copied to ~/Desktop/Tuta Workspace/HOREB_SQL_Kiswahili_G<n>.sql). NOT RUN: the owner runs the SQL.
// Build the grades in order (4, 5, ... 9): a prerequisite may name a skill of a grade below, which must be built first.
// Official outcomes and sub-strand text are never touched. Skills 'proposed', misconceptions 'draft', the pack a draft.
// ============================================================================
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync, copyFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { packSlug, packEntries, packFileText } from './maths-teaching-pack-file.mjs';
import { curriculumSql } from './lib/curriculum-sql.mjs';
import { relinkLowerOutcomes, withOutcomeCleanup } from './lib/lower-grade.mjs';

const ROOT = new URL('..', import.meta.url).pathname;
const GRADE = Number(process.argv[2]);
const ONLY_AWAITING = process.argv.includes('--awaiting');
if (![1, 2, 3, 4, 5, 6, 7, 8, 9].includes(GRADE)) { console.error('usage: node scripts/build-kiswahili-grade.mjs 1|2|...|9'); process.exit(1); }
// Grades 1 to 3 (18 Nov 2026) had KICD outcomes only: no first pass, no families; every skill comes from the depth layer.
const LOWER = GRADE <= 3;
const NOT_TESTED = /^\s*(kuchangamkia|kufurahia|kuonea fahari|kuthamini|kujenga mazoea|kukuza mazoea|kuridhia|ufurahia)/i;
const fail = (msg) => { throw new Error(`Kiswahili Grade ${GRADE}: ${msg}`); };
const run = (args) => { const r = spawnSync('node', args, { stdio: 'inherit', cwd: ROOT }); if (r.status) process.exit(r.status); };

// The skills of this grade with no question family yet, read in a fresh process after the map is rebuilt.
async function writeAwaiting() {
  const entry = (await import(`../src/ai-tutor/content/subjects/kiswahili_g${GRADE}.js`)).default;
  const used = new Set(entry.families.map(f => f.cskill));
  const list = Object.keys(entry.map.skills).filter(c => !used.has(c));
  writeFileSync(join(ROOT, `src/ai-tutor/content/families/kiswahili_g${GRADE}_awaiting.js`),
    `// GENERATED by scripts/build-kiswahili-grade.mjs ${GRADE}. Do not edit by hand.\n` +
    `// The Grade ${GRADE} Kiswahili skills that have no question family yet (${list.length} of ${Object.keys(entry.map.skills).length}).\n` +
    `// The checks list them for the family writers instead of failing; a skill that gets a family must leave this list (rebuild).\n` +
    `export const AWAITING = ${JSON.stringify(list, null, 1)};\n`);
  console.log(`kiswahili g${GRADE}: ${list.length} skills with no family yet`);
}
if (ONLY_AWAITING) { await writeAwaiting(); process.exit(0); }

// ---- 1. the first pass (Grades 4 to 9 only)
if (!LOWER) run([`scripts/build-kiswahili-g${GRADE}.mjs`]);

// ---- 2. the depth layer
const load = (g) => JSON.parse(readFileSync(join(ROOT, `curriculum/kiswahili/g${g}.json`), 'utf8'));
const FILE = join(ROOT, `curriculum/kiswahili/g${GRADE}.json`);
const cur = load(GRADE);
const { ADD, NEW, NOTES = {}, READINESS } = await import(`./data/kiswahili-g${GRADE}/index.mjs`);
if (LOWER) for (const s of cur.sub_strands) { s.skills = []; s.misconceptions = []; }   // rebuilt from the depth layer every run
// Grade 1 reaches below the curriculum with pre-primary readiness skills it defines itself (KISW.PP2.READINESS.*, ref 'PP:<ID>'),
// as Maths Grade 1 does (MATH.PP2.READINESS.*): for a teacher to confirm against the PP2 design.
if (READINESS) cur.readiness = READINESS.map(r => ({ code: `KISW.PP2.READINESS.${r.id}`, name: r.name, what: r.what, status: 'proposed' }));
const READY = new Set((cur.readiness || []).map(r => r.code));
const P = `KISW.G${GRADE}.`;
const below = {};
for (let g = 1; g < GRADE; g++) {
  const j = load(g);
  below[g] = { skills: new Set(j.sub_strands.flatMap(s => (s.skills || []).map(k => k.code))), outcomes: new Set(j.sub_strands.flatMap(s => s.outcomes.map(o => o.code))) };
}
const subOf = (key) => cur.sub_strands.find(s => s.code === `${P}${key}`) || fail(`no sub-strand ${key}`);
const skillAt = new Map();   // 'SUB.ID' -> { k, s }
for (const s of cur.sub_strands) for (const k of s.skills) skillAt.set(k.code.slice(P.length), { k, s });
const shorts = new Set(cur.sub_strands.flatMap(s => s.misconceptions.map(m => m.code.slice(m.skill.length + 1))));
const outcomeOf = (s, ref) => {
  const i = ref.lastIndexOf('.');
  const sub = i < 0 ? s : subOf(ref.slice(0, i)), letter = i < 0 ? ref : ref.slice(i + 1);
  return (sub.outcomes.find(o => o.letter === letter || o.code === `${sub.code}.${letter}`) || fail(`no outcome ${ref} for ${s.code}`)).code;
};

const LEADS = cur.sub_strands.some(s => s.skills.some(k => k.leads_to));   // Grade 4 skills also name the Grade 5 skills they lead to
const work = [];
for (const n of NEW) {
  const s = subOf(n.sub), ref = `${n.sub}.${n.id}`;
  if (skillAt.has(ref)) fail(`new skill ${ref} already exists`);
  if (!/8 of 10/.test(n.mastery) || n.mastery.length < 60) fail(`${ref}: the mastery rule must be full and name 8 of 10`);
  const k = { code: `${s.code}.${n.id}`, name: n.name, outcomes: n.outcomes.map(o => outcomeOf(s, o)), mastery: n.mastery, question_forms: n.question_forms, thinking: n.thinking, horeb_skill_ids: [], prerequisites: [], ...(LEADS ? { leads_to: [] } : {}), status: 'proposed' };
  s.skills.push(k); skillAt.set(ref, { k, s }); work.push({ k, s, d: n });
}
for (const a of ADD) {
  const hit = skillAt.get(a.ref) || fail(`no first-pass skill ${a.ref}`);
  if (work.some(w => w.k === hit.k)) fail(`${a.ref} deepened twice`);
  for (const o of a.also || []) { const c = outcomeOf(hit.s, o); if (!hit.k.outcomes.includes(c)) hit.k.outcomes.push(c); }
  work.push({ ...hit, d: a });
}
for (const s of cur.sub_strands) for (const k of s.skills) if (!work.some(w => w.k === k)) fail(`${k.code} has no depth entry (prerequisites, misconceptions, teaching pack)`);

const resolve = (s, r) => {
  if (r.startsWith('PP:')) { const code = `KISW.PP2.READINESS.${r.slice(3)}`; if (!READY.has(code)) fail(`unknown readiness skill ${code}`); return [code, 'skill']; }
  const m = /^G(\d)(o?):(.+)$/.exec(r);
  if (m) {
    const g = Number(m[1]), b = below[g] || fail(`prerequisite ${r}: Grade ${g} is not below`);
    if (m[2]) { const code = `KISW.G${g}.${m[3]}`; if (!b.outcomes.has(code)) fail(`unknown Grade ${g} outcome ${code}`); return [code, 'outcome']; }
    const code = `KISW.G${g}.${m[3]}`; if (!b.skills.has(code)) fail(`unknown Grade ${g} skill ${code}`); return [code, 'skill'];
  }
  const ref = r.startsWith('.') ? `${s.code.slice(P.length)}${r}` : r;
  return [(skillAt.get(ref) || fail(`unknown Grade ${GRADE} skill ${ref}`)).k.code, 'skill'];
};
const packs = new Map();   // sub-strand code -> { suffix: pack }
for (const { k, s, d } of work) {
  for (const [r, strength, reason] of d.pre || []) {
    const [requires, kind] = resolve(s, r);
    if (requires === k.code) fail(`${k.code} requires itself`);
    if (k.prerequisites.some(x => x.requires === requires)) fail(`${k.code}: prerequisite ${requires} twice`);
    if (!reason || reason.length < 12) fail(`${k.code}: prerequisite ${r} needs a reason`);
    k.prerequisites.push({ requires, kind, strength, reason, status: 'proposed', grade: READY.has(requires) ? 0 : Number(/^KISW\.G(\d)\./.exec(requires)[1]) });
  }
  for (const x of d.mis || []) {
    if (shorts.has(x.short)) fail(`misconception code ${x.short} is used twice in Grade ${GRADE}`);
    if (!x.short.startsWith(`M${GRADE}_`)) fail(`${x.short}: depth-layer codes start M${GRADE}_ so the joined Kiswahili maps never clash`);
    if (x.example.wrong_answer === x.example.correct_answer) fail(`${x.short}: the wrong answer is the right one`);
    for (const f of ['error', 'cause', 'help', 'feedback', 'ask']) if (!x[f] || x[f].length < 6) fail(`${x.short}: ${f} missing`);
    shorts.add(x.short);
    s.misconceptions.push({ code: `${k.code}.${x.short}`, skill: k.code, error: x.error, example: x.example, cause: x.cause, reveals: x.reveals, help: x.help, feedback: x.feedback, source: x.source, status: 'draft' });
  }
  if (!d.pack) fail(`${k.code}: no teaching pack entry`);
  const suffix = k.code.slice(s.code.length + 1), mis = {};
  for (const mm of s.misconceptions.filter(y => y.skill === k.code)) {
    const short = mm.code.slice(k.code.length + 1), own = (d.mis || []).find(y => y.short === short), fx = (d.fix || {})[short];
    const ask = own ? own.ask : fx ? fx[0] : `Soma tena: "${mm.example.question}" Kwa nini "${mm.example.wrong_answer}" si jibu sahihi?`;
    const repair = own ? own.repair : fx ? fx[1] : mm.feedback;
    mis[short] = [[String(mm.example.wrong_answer).slice(0, 80)], ask, repair];
  }
  (packs.get(s.code) || packs.set(s.code, {}).get(s.code))[suffix] = { ...d.pack, mis };
}

// Grades 4 to 9 (19 Nov 2026): Grade 1-3 outcome prerequisites (the Grade 4 first pass named Grade 3 outcomes) name the Grade 1-3
// skill that carries them, now that Grades 1-3 have skills (scripts/lib/lower-grade.mjs). Two outcomes of one skill stay one.
if (!LOWER) {
  const relink = relinkLowerOutcomes(cur, { root: ROOT, label: `Kiswahili Grade ${GRADE}` });
  console.log(`kiswahili g${GRADE}: ${relink.moved} Grade 1-3 outcome prerequisites now name skills (${relink.merged} merged), ${relink.kept.length} kept as outcomes`);
}

// ---- 3. the standard
const covered = new Set(cur.sub_strands.flatMap(s => s.skills.flatMap(k => k.outcomes)));   // a skill may carry an outcome of another sub-strand (the same kind of insha in two themes)
for (const s of cur.sub_strands) {
  if (!s.skills.length) fail(`${s.code} has no skill`);
  const left = s.outcomes.filter(o => !covered.has(o.code) && !NOT_TESTED.test(o.text)).map(o => o.letter);
  if (left.length) fail(`${s.code}: testable outcomes with no skill: ${left.join(', ')}`);
  for (const k of s.skills) {
    if (k.prerequisites.length < 2) fail(`${k.code}: only ${k.prerequisites.length} prerequisites`);
    const n = s.misconceptions.filter(y => y.skill === k.code).length;
    if (n < 4) fail(`${k.code}: only ${n} misconceptions`);
  }
}

// ---- 4. write
const PACK_DIR = join(ROOT, `curriculum/kiswahili/teaching/g${GRADE}/`);
mkdirSync(PACK_DIR, { recursive: true });
const status = `draft: written 18 Nov 2026 offline for Grade ${GRADE} Kiswahili; not yet checked by a native Kiswahili teacher; not loaded by the live tutor`;
const written = new Set();
for (const s of cur.sub_strands) {
  const slug = packSlug(s), pk = packs.get(s.code);
  writeFileSync(join(PACK_DIR, slug), packFileText(s, packEntries(s, s.skills.map(k => k.code.slice(s.code.length + 1)), pk), status, NOTES[s.code.slice(P.length)] || ''));
  written.add(slug);
}
for (const f of readdirSync(PACK_DIR)) if (f.endsWith('.json') && !written.has(f)) unlinkSync(join(PACK_DIR, f));
const all = cur.sub_strands;
cur.totals = { ...cur.totals, skills: all.reduce((n, s) => n + s.skills.length, 0), prerequisites: all.reduce((n, s) => n + s.skills.reduce((m, k) => m + k.prerequisites.length, 0), 0), misconceptions: all.reduce((n, s) => n + s.misconceptions.length, 0) };
cur.status = LOWER ? `outcomes from KICD's text, word for word; skills and prerequisites proposed, misconceptions draft, teaching pack draft; mapped to the Grade 5 Maths standard on 18 Nov 2026 (two prerequisites and four misconceptions per skill; the file had outcomes only); written offline by Claude, awaiting a native Kiswahili teacher's review` : `outcomes from KICD's text, word for word; skills and prerequisites proposed, misconceptions draft, teaching pack draft; first pass 12 and 13 Nov 2026, deepened to the Grade 5 Maths standard on 18 Nov 2026 (two prerequisites and four misconceptions per skill); written offline by Claude, awaiting a native Kiswahili teacher's review`;
writeFileSync(FILE, JSON.stringify(cur, null, 1) + '\n');
console.log(`kiswahili g${GRADE} depth: ${cur.totals.skills} skills, ${cur.totals.prerequisites} prerequisites, ${cur.totals.misconceptions} misconceptions, ${written.size} teaching pack files`);

run(['scripts/build-subject-map.mjs', 'kiswahili', String(GRADE), '--dir', 'kiswahili', '--title', 'Kiswahili']);
run(['scripts/build-kiswahili-grade.mjs', String(GRADE), '--awaiting']);

const MIG = `20261125_kiswahili_g${GRADE}_skills_misconceptions.sql`;
const sql = curriculumSql(cur, {
  title: `Grade ${GRADE} Kiswahili`, when: 'owner, 18 Nov 2026', after: `20261110_curriculum.sql (the five curriculum tables); the Kiswahili grades in order, ${LOWER ? '1' : '4'} to 9 (prerequisites name the grade below; there is no foreign key on them, so the order is for the reviewer only)`,
  why: LOWER ? `Kiswahili Grade ${GRADE} had KICD outcomes only (curriculum/kiswahili/g${GRADE}.json: no skills, no families); on 18 Nov 2026 it was mapped to the Grade 5 Maths standard (a skill for every testable outcome, two prerequisites and four misconceptions per skill, a teaching pack)${GRADE === 1 ? '; prerequisites below Grade 1 name pre-primary readiness skills defined in g1.json (readiness), for a teacher to confirm' : ''}.` : `Kiswahili Grade ${GRADE} had a first-pass map in the repository (curriculum/kiswahili/g${GRADE}.json) that no migration loaded; on 18 Nov 2026 it was brought to the Grade 5 Maths standard (a skill for every sub-strand, two prerequisites and four misconceptions per skill, a teaching pack).`,
  generator: `scripts/build-kiswahili-grade.mjs ${GRADE}`, source: `curriculum/kiswahili/g${GRADE}.json`,
});
writeFileSync(join(ROOT, 'supabase/migrations', MIG), LOWER ? sql.text : withOutcomeCleanup(sql.text, cur, `KISW.G${GRADE}.%`));   // drop outcome prerequisites an earlier run wrote
const WS = join(homedir(), 'Desktop', 'Tuta Workspace');
if (existsSync(WS)) copyFileSync(join(ROOT, 'supabase/migrations', MIG), join(WS, `HOREB_SQL_Kiswahili_G${GRADE}.sql`));
console.log(`SQL: ${MIG} (${sql.skills} skills, ${sql.prerequisites} prerequisites, ${sql.misconceptions} misconceptions)${existsSync(WS) ? `, copied to Tuta Workspace/HOREB_SQL_Kiswahili_G${GRADE}.sql` : ''}`);

// Writes the Grade 4 Maths review document for a teacher: docs/qa/maths-g4-<date>.md. Free, local, counts and codes only.
//   node scripts/maths-g4-review-doc.mjs
import { writeFileSync } from 'node:fs';
import { FAMILIES } from '../src/ai-tutor/content/families/index.js';
import { drawFamily, setFamilyMode } from '../src/ai-tutor/content/families/core.js';
import { SKILLS_G4 } from '../src/ai-tutor/content/curriculumMap.g4.js';
import { OUTCOMES } from '../src/ai-tutor/curriculum/outcomes.js';
import { formText, clusterForms } from '../engine/scripts/content_measures.mjs';
import { LETTERS, SUB_OF, TEXT_FIXES } from './data/maths-g4-letters.mjs';
import { readFileSync } from 'node:fs';

const g4 = JSON.parse(readFileSync(new URL('../curriculum/mathematics/g4.json', import.meta.url), 'utf8'));
const DATE = new Date().toISOString().slice(0, 10);
setFamilyMode('all');
const warn = console.warn; console.warn = () => {};
const mine = FAMILIES.filter(f => f.cskill && /^MATH\.G4\./.test(f.cskill));
const out = [];
const P = (s = '') => out.push(s);
const ATT = /^(appreciate|use digital|use it )/i;
const skills = g4.sub_strands.flatMap(s => s.skills), mis = g4.sub_strands.flatMap(s => s.misconceptions), pre = skills.flatMap(k => k.prerequisites);
const lit = mis.filter(m => /^widely reported/.test(m.source)).length;
const newFams = mine.filter(f => /^g4c\./.test(f.id)), oldFams = mine.filter(f => !/^g4c\./.test(f.id));
const outcomes = g4.sub_strands.flatMap(s => s.outcomes.map(o => ({ ...o, sub: s.sub_strand })));

P(`# Mathematics Grade 4 depth: skills, prerequisites, misconceptions, families (${DATE})`);
P();
P('Generated by `node scripts/maths-g4-review-doc.mjs`. Free and local: no model calls, no learner data. **Everything here is a draft for a CBC Grade 4 teacher to review. Nothing reaches a child:** every family is `reviewed: false`, and the skills, prerequisites and misconceptions are proposed or draft.');
P();
P('Source: KICD Grade 4 Mathematics Curriculum Design (revised 2024), read from the PDF text layer in `docs/curriculum-sources`. The map is `curriculum/mathematics/g4.json` (HOREB owns it); Tuta keeps a generated read copy (`curriculumMap.g4.js`). Built by `scripts/build-maths-g4.mjs` from `scripts/data/maths-g4-*.mjs`, then `scripts/build-curriculum-map-g4.mjs`.');
P();
P('## Counts');
P();
P('| What | Count |');
P('|---|---|');
P(`| Sub-strands | ${g4.sub_strands.length} |`);
P(`| Official outcomes (unchanged) | ${outcomes.length} (${outcomes.filter(o => ATT.test(o.text)).length} attitude or digital-use, not testable by a typed answer) |`);
P(`| Skills | ${skills.length} (${skills.filter(k => k.hands_on).length} with a hands-on side; ${skills.filter(k => k.hands_on && !k.question_forms.length).length} that a typed answer cannot test at all) |`);
P(`| Prerequisites | ${pre.length} (${pre.filter(r => r.kind === 'outcome').length} to Grade 3 outcomes, ${pre.filter(r => r.kind === 'skill').length} to other Grade 4 skills; ${pre.filter(r => r.strength === 'essential').length} essential, ${pre.filter(r => r.strength === 'helpful').length} helpful) |`);
P(`| Misconceptions | ${mis.length} (${lit} marked as widely reported in the research literature, ${mis.length - lit} marked "to confirm by a teacher") |`);
P(`| Question families filed under a skill | ${mine.length} (${oldFams.length} written earlier and now linked, ${newFams.length} new) |`);
P();
P('The misconception library is a draft written from common patterns in primary mathematics (place-value slips, carrying errors, unit confusions, fraction and decimal rules). **No entry is yet confirmed as a common error among Kenyan learners:** each one carries a `source` field, and a teacher (or the team psychology graduate) confirms, edits or strikes it. Mastery rule per skill is the `mastery` text in the map; question forms are `question_forms`.');
P();
P('## Sub-strands');
P();
P('| Sub-strand | Outcomes | Skills | Misconceptions | Families | Skills with fewer than 2 structures |');
P('|---|---|---|---|---|---|');
const rows = [];
const structures = {};
for (const [code, k] of Object.entries(SKILLS_G4)) {
  const fams = mine.filter(f => f.cskill === code), texts = [];
  for (const f of fams) for (let i = 0; i < 20; i++) { try { texts.push(formText(drawFamily(f).p)); } catch { /* checked elsewhere */ } }
  structures[code] = { families: fams.length, forms: new Set(fams.map(f => f.form)).size, structures: fams.length ? clusterForms(texts).length : 0 };
}
for (const s of g4.sub_strands) {
  const ks = s.skills.map(k => structures[k.code]);
  P(`| ${s.sub_strand} | ${s.outcomes.length} | ${s.skills.length} | ${s.misconceptions.length} | ${ks.reduce((a, x) => a + x.families, 0)} | ${s.skills.filter((k, i) => !(k.hands_on && !k.question_forms.length) && (ks[i].families < 2 || ks[i].structures < 2)).length} |`);
}
P();
P('## Skills');
P();
P('E = essential prerequisite, H = helpful. G3 = Grade 3 outcomes the skill builds on. Fam = question families, Str = different question structures in a sample of draws (a measure of variety, not a verdict).');
for (const s of g4.sub_strands) {
  P();
  P(`### ${s.strand}: ${s.sub_strand}`);
  P();
  P('| Skill | Outcomes | HOREB skill | Prerequisites | Misc. | Fam | Str |');
  P('|---|---|---|---|---|---|---|');
  for (const k of s.skills) {
    const st = structures[k.code], p = k.prerequisites;
    P(`| ${k.name}${k.hands_on ? (k.question_forms.length ? ' (hands-on side)' : ' (hands-on only)') : ''} | ${k.outcomes.map(o => o.split('.').pop()).join(', ')} | ${k.horeb_skill_ids.join(', ')} | G3 ${p.filter(r => r.kind === 'outcome').map(r => r.requires.replace(/^MATH\.G3\.\w+\./, '')).join(', ') || '-'}; G4 E${p.filter(r => r.kind === 'skill' && r.strength === 'essential').length} H${p.filter(r => r.kind === 'skill' && r.strength === 'helpful').length} | ${s.misconceptions.filter(m => m.skill === k.code).length} | ${st.families} | ${st.structures} |`);
  }
}
P();
P('## Outcomes with no skill');
P();
const noSkill = outcomes.filter(o => !skills.some(k => k.outcomes.includes(o.code)));
P(`${noSkill.length} outcomes have no skill: ${noSkill.filter(o => ATT.test(o.text)).length} attitude or digital-use outcomes (appreciate..., use digital devices...), which no typed question can test. ${noSkill.filter(o => !ATT.test(o.text)).length} testable outcomes have none.`);
P();
P('## Hands-on outcomes: what a typed or tapped answer cannot test');
P();
for (const k of skills.filter(k => k.hands_on)) P(`- **${k.name}** (${k.outcomes.map(o => o.split('.').pop()).join(', ')}): ${k.hands_on}${k.question_forms.length ? ' The typed families test the thinking only.' : ' No typed family: it stays with paper and the teacher.'}`);
P();
P('## HOREB outcome letters reconciled with the official ones');
P();
P('HOREB\'s own Grade 4 list (`src/ai-tutor/curriculum/outcomes.js`, ids like `G4.SUB.a`) was written before the official letters were read. Families written earlier are now filed under the official outcome code (`MATH.G4.NUMBER.SUBTRACTION.b`) and the curriculum skill. Differences found:');
P();
P('**Text fixed in `outcomes.js`:**');
P();
P('| HOREB id | Was | Now | Why |');
P('|---|---|---|---|');
for (const [id, was, now, why] of TEXT_FIXES) P(`| ${id} | ${was} | ${now} | ${why} |`);
P();
P('**One HOREB letter stands for several official letters (folded):**');
P();
P('| HOREB id | Official letters |');
P('|---|---|');
for (const [id, ls] of Object.entries(LETTERS)) if (ls.length > 1) P(`| G4.${id} | ${ls.join(', ')} (${ls.map(l => outcomes.find(o => o.code === `MATH.G4.${SUB_OF[id.split('.')[0]]}.${l}`)?.text).join('; ').slice(0, 170)}) |`);
P();
P('**Official outcomes HOREB\'s list never had** (testable ones; attitude and digital ones are left out on purpose): ');
P();
const named = new Set(Object.entries(LETTERS).flatMap(([id, ls]) => ls.map(l => `MATH.G4.${SUB_OF[id.split('.')[0]]}.${l}`)));
for (const o of outcomes.filter(o => !named.has(o.code) && !ATT.test(o.text))) P(`- ${o.code.replace('MATH.G4.', '')}: ${o.text}`);
P();
P('**Sub-strand code:** HOREB files Use of letters under Algebra (`MATH.G4.ALGEBR.USE_OF_LETTERS`); KICD files it under Numbers (`MATH.G4.NUMBER.USE_OF_LETTERS`). The coverage report joins them by an alias; the ids in `outcomes.js` are left as they are because families and skill tags carry them.');
P();
P('**Official text left for a person to confirm** (status `kicd_read`, from the PDF text layer): ' + outcomes.filter(o => o.status === 'kicd_read' && !ATT.test(o.text)).map(o => o.code.replace('MATH.G4.', '')).join(', ') + '.');
P();
P('**Garbled in the text layer:** Capacity outcome b reads "litres and litres"; the design\'s own competence text says half-litre and quarter-litre containers, so the skill is written for those. Please confirm against the printed design.');
P();
P('## Families');
P();
const byForm = {}, byRung = {};
for (const f of newFams) { byForm[f.form] = (byForm[f.form] || 0) + 1; byRung[f.rung] = (byRung[f.rung] || 0) + 1; }
P(`${newFams.length} new families (\`src/ai-tutor/content/families/g4c_*.js\`, kit in \`g4c_lib.js\`), ${oldFams.length} older Grade 4 families linked to a skill, an official outcome and the library codes their wrong answers reveal (\`scripts/link-maths-g4-families.mjs\`). Every wrong answer in a new family names the library misconception it reveals, and the checks fail a wrong answer that names none. New families by form: ${Object.entries(byForm).map(([a, b]) => `${a} ${b}`).join(', ')}. By rung: ${Object.entries(byRung).map(([a, b]) => `${a} ${b}`).join(', ')}.`);
P();
P('Wrong answers are produced by running the misconception as a procedure (drop the carry, write the column total, take the smaller digit from the larger, treat 100 minutes as an hour). Where a family\'s wrong answer fits no library entry exactly, it is tied to the nearest one: a teacher should check those links.');
P();
P('Notes for the reviewer, found while linking:');
P('- `g4.num.words-pick` writes amounts up to sh 4,037 in words; official outcome c stops at 1,000. It is filed under outcome b (read numbers up to 10,000).');
P('- `g4.div.spot-check` divides 114 by 6 (a three-digit dividend); outcome a on division stops at a two-digit dividend.');
P('- The older angle families (`g4.angles.*`) use the words acute and obtuse as distractors; the Grade 4 outcomes only name the right angle through quarter turns.');
P('- `g4.sub.estimate-stock` sold "litres" of bottles of soda: fixed to read "of them".');
P('- The practice engine\'s generator skills (G4_*) are unchanged. The families are filed under the generator skill the map names as primary.');
P();
P('## What is not done');
P();
P('- No teacher review. The sign-off ids go in `src/ai-tutor/content/families/g4c_signed.js` (empty); a family stays off for children until it is listed there.');
P('- Homework (`src/school/homework.js`) and the school door still read the Grade 5 map only: a Grade 4 family is in the bank but cannot be set as homework until that code reads `curriculumMap.g4.js`.');
P('- The Supabase curriculum tables (`20261110_curriculum.sql`) are generated from the Grade 5 map only; the Grade 4 map is not loaded there.');
P('- No Grade 4 HTML review pack: the G5 pack builder is Grade 5 only. This document is the review list until one is built.');
console.warn = warn;
const path = new URL(`../docs/qa/maths-g4-${DATE}.md`, import.meta.url);
writeFileSync(path, out.join('\n') + '\n');
console.log(`written docs/qa/maths-g4-${DATE}.md`);

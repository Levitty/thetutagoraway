// ============================================================================
// Writes the Grade 5 Science and Technology curriculum map, the same shape as Maths:
//   src/ai-tutor/content/curriculumMap.science.g5.js   light: sub-strands, official outcomes, skills,
//                                                       and MIS_FEEDBACK (the child-facing line for each
//                                                       misconception, read by the question families)
//   engine/data/curriculum/science.g5.misconceptions.json   heavy: the misconception library (checks and review pack)
//   engine/data/curriculum/science.g5.detail.json            heavy: outcome texts, mastery rules, question forms
// Source: curriculum/science/g5.json (HOREB owns it). Outcomes are official (KICD, word for word);
// skills, prerequisites and misconceptions are proposed or draft until a teacher reviews them.
//   node scripts/build-curriculum-map-science.mjs
// A science family carries `cskill` (a key of SKILLS_SCI_G5) and `outcome` (its official outcome code).
// Science skills are not in the practice engine's SKILLS, so a family's `skill` is its cskill.
// ============================================================================
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = process.argv[2] || fileURLToPath(new URL('../curriculum/science/g5.json', import.meta.url));
const g5 = JSON.parse(readFileSync(src, 'utf8'));
const out = { source: 'curriculum/science/g5.json', status: g5.status, subs: {}, outcomes: {}, skills: {} };
const mis = {}, detail = { outcomes: {}, skills: {} }, fb = {};
const G5_SKILLS = new Set(g5.sub_strands.flatMap(x => x.skills.map(k => k.code)));
for (const s of g5.sub_strands) {
  out.subs[s.code] = { name: s.sub_strand, strand: s.strand, outcomes: s.outcomes.map(o => o.code) };
  for (const o of s.outcomes) { out.outcomes[o.code] = { letter: o.letter, sub: s.code }; detail.outcomes[o.code] = o.text; }
  for (const k of s.skills) {
    out.skills[k.code] = { name: k.name, sub: s.code, outcome: k.outcomes[0], outcomes: k.outcomes, pre: [...new Set((k.prerequisites || []).map(r => r.requires).filter(c => G5_SKILLS.has(c)))], mis: [] };
    detail.skills[k.code] = { forms: k.question_forms, mastery: k.mastery };
  }
  for (const m of s.misconceptions) {
    const short = m.code.slice(m.skill.length + 1);
    if (fb[short]) throw new Error(`duplicate misconception code ${short}`);
    out.skills[m.skill].mis.push(short);
    mis[m.code] = { skill: m.skill, error: m.error, example: m.example, cause: m.cause, reveals: m.reveals, help: m.help, feedback: m.feedback, source: m.source, status: m.status };
    fb[short] = m.feedback;
  }
}
const header = `// GENERATED by scripts/build-curriculum-map-science.mjs from curriculum/science/g5.json (KICD Science and Technology, Grade 5). Do not edit by hand.
// Outcomes are official (word for word). Skills are proposed, awaiting teacher review.
// A science family carries \`cskill\` (a key of SKILLS_SCI_G5), \`outcome\` (its official outcome) and \`skill\` (the same as cskill:
// science skills are not in the practice engine yet). MIS_FEEDBACK maps a short misconception code to the line a child reads.
`;
writeFileSync(new URL('../src/ai-tutor/content/curriculumMap.science.g5.js', import.meta.url), `${header}export const SCI_MAP_SOURCE = ${JSON.stringify({ source: out.source, status: out.status })};
export const SUBSTRANDS_SCI_G5 = ${JSON.stringify(out.subs, null, 1)};
export const OUTCOMES_SCI_G5 = ${JSON.stringify(out.outcomes, null, 1)};
export const SKILLS_SCI_G5 = ${JSON.stringify(out.skills, null, 1)};
export const MIS_FEEDBACK = ${JSON.stringify(fb, null, 1)};
`);
writeFileSync(new URL('../engine/data/curriculum/science.g5.misconceptions.json', import.meta.url), JSON.stringify(mis, null, 1) + '\n');
writeFileSync(new URL('../engine/data/curriculum/science.g5.detail.json', import.meta.url), JSON.stringify(detail, null, 1) + '\n');
console.log(`science g5 map: ${Object.keys(out.subs).length} sub-strands, ${Object.keys(out.outcomes).length} outcomes, ${Object.keys(out.skills).length} skills, ${Object.keys(mis).length} misconceptions`);

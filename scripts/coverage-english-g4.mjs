// ============================================================================
// OUTCOME COVERAGE, ENGLISH GRADE 5: free, local, no model calls.
//   node scripts/coverage-english-g4.mjs            writes docs/qa/coverage-english-g4-<date>.md
//   node scripts/coverage-english.mjs --json   prints the numbers only
// For every official outcome in curriculum/english/g4.json: is it checked by question families, or does
// it need composition marking, a teacher or a voice tool? Counts and outcome codes only.
// The route of an outcome that no family covers is decided by the rules in scripts/data/english-g4-routes.mjs.
// ============================================================================
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { routeOf, ROUTE_NAMES, COMPOSITION_TYPE } from './data/english-g4-routes.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const JSON_ONLY = process.argv.includes('--json');
const DATE = new Date().toISOString().slice(0, 10);
const g4 = JSON.parse(readFileSync(resolve(root, 'curriculum/english/g4.json'), 'utf8'));
const { entryFor } = await import(resolve(root, 'src/ai-tutor/content/subjects/registry.js'));
const ENGLISH_FAMILIES = entryFor('english', 4).families;
const { drawFamily } = await import(resolve(root, 'src/ai-tutor/content/families/core.js'));

const famBy = new Map(), skillBy = new Map();
const famOfSkill = new Map();
for (const f of ENGLISH_FAMILIES) (famOfSkill.get(f.cskill) || famOfSkill.set(f.cskill, []).get(f.cskill)).push(f);
// An outcome is covered when a skill that lists it has families: the design repeats some outcomes in later themes and one skill serves them all.
for (const s of g4.sub_strands) for (const k of s.skills) for (const o of k.outcomes) {
  (skillBy.get(o) || skillBy.set(o, []).get(o)).push(k.code);
  for (const f of famOfSkill.get(k.code) || []) (famBy.get(o) || famBy.set(o, []).get(o)).push(f);
}
const misBy = new Map();
for (const s of g4.sub_strands) for (const m of s.misconceptions) { const k = s.skills.find(x => x.code === m.skill); for (const o of k.outcomes) misBy.set(o, (misBy.get(o) || 0) + 1); }
// Does a draw carry feedback for a wrong answer? (every family is built that way: checked by english_checks.mjs)
const sampleOk = (f) => { try { const p = drawFamily(f).p; return !!(p.misconceptions || []).some(m => m.feedback) || !!p.mis; } catch { return false; } };

const rows = [];
for (const s of g4.sub_strands) for (const o of s.outcomes) {
  const fams = famBy.get(o.code) || [];
  const route = fams.length ? 'family' : routeOf(o, s);
  rows.push({ code: o.code, sub: s.code, strand: s.strand, letter: o.letter, text: o.text, families: fams.length, kinds: new Set(fams.map(f => f.kind)).size, mis: misBy.get(o.code) || 0, skills: (skillBy.get(o.code) || []).length, route, composition: route === 'composition' ? COMPOSITION_TYPE(o, s) : '', fb: fams.length ? fams.every(sampleOk) : null });
}
const count = (fn) => rows.filter(fn).length;
const byRoute = Object.fromEntries(Object.keys(ROUTE_NAMES).map(r => [r, count(x => x.route === r)]));
const summary = { date: DATE, outcomes: rows.length, byRoute, families: ENGLISH_FAMILIES.length, skills: [...skillBy.values()].flat().filter((v, i, a) => a.indexOf(v) === i).length, withFamilyTwoKinds: count(x => x.kinds >= 2), withFamilyOneKind: count(x => x.kinds === 1), feedbackOk: count(x => x.fb === true) };
if (JSON_ONLY) { console.log(JSON.stringify(summary, null, 1)); process.exit(0); }

const out = [], P = (s = '') => out.push(s);
P(`# Outcome coverage, English Grade 4 (${DATE})`);
P();
P('Generated by `node scripts/coverage-english-g4.mjs` (`scripts/coverage-english-g4.mjs`). Free and local: no model calls. Counts and outcome codes only.');
P();
P(`Official outcomes come from \`curriculum/english/g4.json\` (${rows.length} outcomes in ${g4.sub_strands.length} sub-strands, all KICD text). Every outcome has one **route**: a question **family** (${ENGLISH_FAMILIES.length} draft families in the bank, none switched on for children), **composition marking** (HOREB's English composition marker, four bands out of 20), **voice or a teacher** (speaking, listening and sounds, which a typed answer cannot test), **a teacher only** (reading habits, handwriting, forms, opinions) or **attitude** (an outcome about caring, advocating or recommending).`);
P();
P('## Outcomes by route');
P();
P('| Route | Outcomes | What it means |');
P('|---|---|---|');
for (const [r, name] of Object.entries(ROUTE_NAMES)) P(`| ${name.title} | ${byRoute[r]} | ${name.means} |`);
P(`| **All** | **${rows.length}** | |`);
P();
P(`Outcomes with a family: ${byRoute.family}. Of these ${summary.withFamilyTwoKinds} have families of two or more different structures and ${summary.withFamilyOneKind} have one structure (see the table below). Every wrong answer in every family names a misconception of the library.`);
P();
P('## By strand');
P();
P('| Strand | Outcomes | Family | Composition | Voice | Teacher | Attitude |');
P('|---|---|---|---|---|---|---|');
for (const strand of [...new Set(rows.map(r => r.strand))]) {
  const L = rows.filter(r => r.strand === strand);
  P(`| ${strand} | ${L.length} | ${L.filter(r => r.route === 'family').length} | ${L.filter(r => r.route === 'composition').length} | ${L.filter(r => r.route === 'voice').length} | ${L.filter(r => r.route === 'teacher').length} | ${L.filter(r => r.route === 'attitude').length} |`);
}
P();
P('## Every outcome');
P();
P('Columns: route, Fam = families, Str = different structures, Mis = library misconceptions on the skill that covers it, Marks = composition type for the writing marker.');
for (const s of g4.sub_strands) {
  P();
  P(`### ${s.code.replace('ENGL.G4.', '')}: ${s.sub_strand}`);
  P();
  P('| Outcome | Route | Fam | Str | Mis | Marks | Outcome text |');
  P('|---|---|---|---|---|---|---|');
  for (const r of rows.filter(x => x.sub === s.code)) P(`| ${r.letter} | ${ROUTE_NAMES[r.route].title} | ${r.families || '.'} | ${r.kinds || '.'} | ${r.mis || '.'} | ${r.composition || '.'} | ${r.text.replace(/\|/g, '/').slice(0, 100)} |`);
}
writeFileSync(resolve(root, `docs/qa/coverage-english-g4-${DATE}.md`), out.join('\n') + '\n');
console.log(`written docs/qa/coverage-english-g4-${DATE}.md`);
console.table({ outcomes: rows.length, ...byRoute, families: ENGLISH_FAMILIES.length });

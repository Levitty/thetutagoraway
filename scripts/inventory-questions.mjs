// ============================================================================
// QUESTION BANK INVENTORY — what HOREB can ask today, skill by skill.
//   node scripts/inventory-questions.mjs > docs/qa/question-bank-inventory.md
// For every skill (all levels and sub-steps): distinct question forms, variety,
// whether it has a picture, a worked example, hints, misconception feedback,
// tap-buttons, and a sample question.
// ============================================================================
import { SKILLS } from '../src/ai-tutor/knowledgeGraph.js';
import { generateProblem } from '../src/ai-tutor/problemGenerators.js';

const N = 80;
const rows = [];
for (const [id, s] of Object.entries(SKILLS)) {
  const t0 = Date.now();
  const qs = new Set(), types = new Map();
  let visual = 0, worked = 0, hints = 0, misc = 0, choices = 0, story = 0;
  for (let i = 0; i < N; i++) {
    const p = generateProblem(id, { level: ['abstract', 'pictorial', 'concrete'][i % 3], kp: i % 2 ? (i >> 1) % 6 : undefined });
    if (!p) continue;
    qs.add(p.question);
    const t = p.type || '(untyped)';
    if (!types.has(t)) types.set(t, p.question.replace(/\s+/g, ' ').slice(0, 90));
    if (p.visual) visual++;
    if (p.workedExample) worked++;
    if ((p.hints && p.hints.length) || p.hint) hints++;
    if (p.misconceptions && p.misconceptions.length) misc++;
    if (p.choices) choices++;
    if (/[A-Z][a-z]+ (has|buys|bought|walks|walked|sells|shares|pays|travels|uses|gets)|KSh|shop|market|farm|school|matatu|bus/i.test(p.question)) story++;
  }
  process.stderr.write(`${id} ${Date.now() - t0}ms\n`);
  const pct = (x) => Math.round(100 * x / N);
  rows.push({ id, grade: s.grade, strand: s.strand, name: s.name, variety: qs.size, types: [...types.entries()], visual: pct(visual), worked: pct(worked), hints: pct(hints), misc: pct(misc), choices: pct(choices), story: pct(story) });
}
rows.sort((a, b) => a.grade - b.grade || a.strand.localeCompare(b.strand));
const tick = (v) => (v >= 50 ? 'yes' : v > 0 ? 'some' : '-');
console.log('# HOREB question bank inventory\n');
console.log(`Generated by \`node scripts/inventory-questions.mjs\`, ${N} questions per skill.\n`);
console.log('Columns: different questions out of 80 · picture · worked example · hints · misconception feedback · tap-buttons · story/context questions.\n');
let g = null;
for (const r of rows) {
  if (r.grade !== g) { g = r.grade; console.log(`\n## Grade ${g}\n\n| Skill | Strand | Different /80 | Picture | Worked ex. | Hints | Misconception fb | Buttons | Story | Forms (sample) |\n|---|---|---|---|---|---|---|---|---|---|`); }
  const forms = r.types.map(([t, q]) => `${t}: ${q.replace(/\|/g, '/')}`).join('<br>');
  console.log(`| ${r.name} (${r.id}) | ${r.strand} | ${r.variety} | ${tick(r.visual)} | ${tick(r.worked)} | ${tick(r.hints)} | ${tick(r.misc)} | ${tick(r.choices)} | ${tick(r.story)} | ${forms} |`);
}
// Summary
const tot = rows.length, low = rows.filter(r => r.variety < 15).length;
const noMisc = rows.filter(r => r.misc === 0).length, noWorked = rows.filter(r => r.worked === 0).length, noVis = rows.filter(r => r.visual === 0).length, noStory = rows.filter(r => r.story === 0).length;
console.log(`\n## Summary\n\n- Skills: ${tot}\n- Fewer than 15 different questions: ${low}\n- No misconception feedback at all: ${noMisc}\n- No worked example: ${noWorked}\n- No picture at any level: ${noVis}\n- No story/context questions: ${noStory}`);

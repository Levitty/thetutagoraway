// ============================================================================
// Writes the Grade 6 Maths curriculum map from curriculum/mathematics/g6.json (HOREB owns it):
//   src/ai-tutor/content/curriculumMap.g6.js        light: sub-strands, official outcomes, skills with HOREB ids, prerequisites
//   engine/data/curriculum/g6.misconceptions.json   heavy: the misconception library (checks and the review pack only)
//   engine/data/curriculum/g6.detail.json           heavy: outcome texts, mastery limits and question forms
//   node scripts/build-curriculum-map-g6.mjs
// Same shape as the Grade 5 map (scripts/build-curriculum-map.mjs). `primary` is the first HOREB skill a skill names.
// ============================================================================
import { readFileSync, writeFileSync } from 'node:fs';
const g6 = JSON.parse(readFileSync(new URL('../curriculum/mathematics/g6.json', import.meta.url), 'utf8'));
const P = 'MATH.G6.';
const out = { source: 'curriculum/mathematics/g6.json', status: g6.status, subs: {}, outcomes: {}, skills: {} };
const mis = {}, detail = { outcomes: {}, skills: {} };
const own = new Set(g6.sub_strands.flatMap(s => (s.skills || []).map(k => k.code)));
const g5 = new Set(JSON.parse(readFileSync(new URL('../curriculum/mathematics/g5.json', import.meta.url), 'utf8')).sub_strands.flatMap(s => s.skills.map(k => k.code)));
for (const s of g6.sub_strands) {
  out.subs[s.code] = { name: s.sub_strand, strand: s.strand, outcomes: s.outcomes.map(o => o.code) };
  for (const o of s.outcomes) { out.outcomes[o.code] = { letter: o.letter, sub: s.code }; detail.outcomes[o.code] = o.text; }
  for (const k of s.skills || []) {
    // pre: the Grade 5 and Grade 6 skills this one builds on, so a tutor can find the weakest one
    const pre = (k.prerequisites || []).map(r => r.requires).filter(c => own.has(c) || g5.has(c));
    out.skills[k.code] = { name: k.name, sub: s.code, outcome: k.outcomes[0], outcomes: k.outcomes, horeb: k.horeb_skill_ids, primary: k.horeb_skill_ids[0], pre: [...new Set(pre)], mis: [], ...(k.hands_on ? { hands: true } : {}) };
    detail.skills[k.code] = { forms: k.question_forms, mastery: k.mastery, ...(k.hands_on ? { hands_on: k.hands_on } : {}) };
  }
  for (const m of s.misconceptions || []) {
    out.skills[m.skill].mis.push(m.code.slice(m.skill.length + 1));
    mis[m.code] = { skill: m.skill, error: m.error, example: m.example, cause: m.cause, reveals: m.reveals, help: m.help, source: m.source, status: m.status };
  }
}
const header = `// GENERATED by scripts/build-curriculum-map-g6.mjs from curriculum/mathematics/g6.json (KICD 2024 design). Do not edit by hand.
// Outcomes are official (verified word for word). Skills are proposed, awaiting teacher review.
// A Grade 6 family carries \`cskill\` (a key of SKILLS_G6 here), \`outcome\` (its official outcome) and its HOREB \`skill\`.
`;
writeFileSync(new URL('../src/ai-tutor/content/curriculumMap.g6.js', import.meta.url), `${header}export const MAP_SOURCE_G6 = ${JSON.stringify({ source: out.source, status: out.status })};
export const SUBSTRANDS_G6 = ${JSON.stringify(out.subs, null, 1)};
export const OUTCOMES_G6 = ${JSON.stringify(out.outcomes, null, 1)};
export const SKILLS_G6 = ${JSON.stringify(out.skills, null, 1)};
export const horebOf6 = (cskill) => [...new Set([...(SKILLS_G6[cskill]?.horeb || []), SKILLS_G6[cskill]?.primary].filter(Boolean))];
`);
writeFileSync(new URL('../engine/data/curriculum/g6.detail.json', import.meta.url), JSON.stringify(detail, null, 1));
writeFileSync(new URL('../engine/data/curriculum/g6.misconceptions.json', import.meta.url), JSON.stringify(mis, null, 1));
console.log(`${Object.keys(out.subs).length} sub-strands, ${Object.keys(out.outcomes).length} outcomes, ${Object.keys(out.skills).length} skills, ${Object.keys(mis).length} misconceptions`);

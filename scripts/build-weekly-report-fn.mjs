// Builds supabase/functions/weekly-report/index.ts from:
//   scripts/weekly-report.template.ts   the function
//   src/family/weeklyReport.js          the report text (shared with the app's preview)
//   engine/data/math_graph.json         skill names
// One self-contained file, so it can be deployed with the CLI or pasted into
// the Supabase dashboard editor. Run after changing any of the three:
//   npm run build:report-fn
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');

const lib = read('src/family/weeklyReport.js')
  .replace(/^export default .*$/m, '')
  .replace(/^export const /gm, 'const ');
const graph = JSON.parse(read('engine/data/math_graph.json'));
const names = Object.fromEntries(
  (Array.isArray(graph.skills) ? graph.skills : Object.values(graph.skills)).map(s => [s.id, s.name]),
);

const out = read('scripts/weekly-report.template.ts')
  .replace('/*__REPORT_LIB__*/', `// ---- from src/family/weeklyReport.js ----\n${lib.trim()}\n// ---- end ----`)
  .replace('/*__SKILL_NAMES__*/', JSON.stringify(names));

const header = '// GENERATED by scripts/build-weekly-report-fn.mjs — do not edit here.\n' +
  '// Edit scripts/weekly-report.template.ts or src/family/weeklyReport.js, then run: npm run build:report-fn\n\n';
mkdirSync(resolve(root, 'supabase/functions/weekly-report'), { recursive: true });
writeFileSync(resolve(root, 'supabase/functions/weekly-report/index.ts'), header + out);
console.log(`weekly-report/index.ts written (${Object.keys(names).length} skill names)`);

// ============================================================================
// Writes the Grade 6, 7 or 8 Maths curriculum map from curriculum/mathematics/g<grade>.json (HOREB owns it):
//   src/ai-tutor/content/curriculumMap.g<grade>.js        light: sub-strands, official outcomes, skills with HOREB ids, prerequisites
//   engine/data/curriculum/g<grade>.misconceptions.json   heavy: the misconception library (checks and the review pack only)
//   engine/data/curriculum/g<grade>.detail.json           heavy: outcome texts, mastery limits and question forms
//   node scripts/build-curriculum-map-grade.mjs 6      (or 7, or 8 and 9: 18 Nov 2026)
// Same shape as the Grade 5 map (scripts/build-curriculum-map.mjs). `primary` is the first HOREB skill a skill names.
// One script for both grades (17 Nov 2026): Grade 7 adds no second copy. A skill's `pre` lists the earlier-grade skills it builds on.
// ============================================================================
import { readFileSync, writeFileSync } from 'node:fs';
const GRADE = Number(process.argv[2] || process.env.MATHS_GRADE);
const BELOW = { 6: [5], 7: [5, 6], 8: [5, 6, 7], 9: [5, 6, 7, 8] }[GRADE];
if (!BELOW) { console.error('usage: node scripts/build-curriculum-map-grade.mjs 6|7|8|9'); process.exit(1); }
const load = (g) => JSON.parse(readFileSync(new URL(`../curriculum/mathematics/g${g}.json`, import.meta.url), 'utf8'));
const cur = load(GRADE);
const P = `MATH.G${GRADE}.`;
const out = { source: `curriculum/mathematics/g${GRADE}.json`, status: cur.status, subs: {}, outcomes: {}, skills: {} };
const mis = {}, detail = { outcomes: {}, skills: {} };
const own = new Set(cur.sub_strands.flatMap(s => (s.skills || []).map(k => k.code)));
const below = new Set(BELOW.flatMap(g => load(g).sub_strands.flatMap(s => s.skills.map(k => k.code))));
for (const s of cur.sub_strands) {
  out.subs[s.code] = { name: s.sub_strand, strand: s.strand, outcomes: s.outcomes.map(o => o.code) };
  for (const o of s.outcomes) { out.outcomes[o.code] = { letter: o.letter, sub: s.code }; detail.outcomes[o.code] = o.text; }
  for (const k of s.skills || []) {
    // pre: the earlier-grade and own skills this one builds on, so a tutor can find the weakest one
    const pre = (k.prerequisites || []).map(r => r.requires).filter(c => own.has(c) || below.has(c));
    out.skills[k.code] = { name: k.name, sub: s.code, outcome: k.outcomes[0], outcomes: k.outcomes, horeb: k.horeb_skill_ids, primary: k.horeb_skill_ids[0], pre: [...new Set(pre)], mis: [], ...(k.hands_on ? { hands: true } : {}) };
    detail.skills[k.code] = { forms: k.question_forms, mastery: k.mastery, ...(k.hands_on ? { hands_on: k.hands_on } : {}) };
  }
  for (const m of s.misconceptions || []) {
    out.skills[m.skill].mis.push(m.code.slice(m.skill.length + 1));
    mis[m.code] = { skill: m.skill, error: m.error, example: m.example, cause: m.cause, reveals: m.reveals, help: m.help, source: m.source, status: m.status };
  }
}
const header = `// GENERATED by scripts/build-curriculum-map-grade.mjs ${GRADE} from curriculum/mathematics/g${GRADE}.json (KICD 2024 design). Do not edit by hand.
// Outcomes are official (verified word for word). Skills are proposed, awaiting teacher review.
// A Grade ${GRADE} family carries \`cskill\` (a key of SKILLS_G${GRADE} here), \`outcome\` (its official outcome) and its HOREB \`skill\`.
`;
writeFileSync(new URL(`../src/ai-tutor/content/curriculumMap.g${GRADE}.js`, import.meta.url), `${header}export const MAP_SOURCE_G${GRADE} = ${JSON.stringify({ source: out.source, status: out.status })};
export const SUBSTRANDS_G${GRADE} = ${JSON.stringify(out.subs, null, 1)};
export const OUTCOMES_G${GRADE} = ${JSON.stringify(out.outcomes, null, 1)};
export const SKILLS_G${GRADE} = ${JSON.stringify(out.skills, null, 1)};
export const horebOf${GRADE} = (cskill) => [...new Set([...(SKILLS_G${GRADE}[cskill]?.horeb || []), SKILLS_G${GRADE}[cskill]?.primary].filter(Boolean))];
`);
writeFileSync(new URL(`../engine/data/curriculum/g${GRADE}.detail.json`, import.meta.url), JSON.stringify(detail, null, 1));
writeFileSync(new URL(`../engine/data/curriculum/g${GRADE}.misconceptions.json`, import.meta.url), JSON.stringify(mis, null, 1));
console.log(`${Object.keys(out.subs).length} sub-strands, ${Object.keys(out.outcomes).length} outcomes, ${Object.keys(out.skills).length} skills, ${Object.keys(mis).length} misconceptions`);

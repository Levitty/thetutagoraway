// Builds supabase/functions/wa-sign-in/index.ts from:
//   scripts/wa-sign-in.template.ts   the wiring (Supabase)
//   src/auth/waSignIn.js             the decisions, tested in node (tests/wa-sign-in.test.mjs)
//
// Run after changing either:  npm run build:wa-sign-in-fn
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');
const LIB = 'src/auth/waSignIn.js';

export const buildWaSignInFn = () => {
  const src = read(LIB);
  const lib = src.replace(/^export (const|function|async function) /gm, '$1 ');
  if (/^\s*(import|export)\s/m.test(lib)) throw new Error(`${LIB}: an import or export the build cannot inline`);
  for (const needed of ['function decideIssue(', 'function doorSignatureOk(', 'function redeemable(', 'const linkUrl =']) {
    if (!lib.includes(needed)) throw new Error(`the inlined library no longer defines: ${needed}`);
  }
  const PLACEHOLDER = '/*__WA_SIGN_IN_LIB__*/';
  const template = read('scripts/wa-sign-in.template.ts');
  if (!template.includes(PLACEHOLDER)) throw new Error(`template is missing ${PLACEHOLDER}`);
  const header = '// GENERATED by scripts/build-wa-sign-in-fn.mjs, do not edit here.\n'
    + '// Edit scripts/wa-sign-in.template.ts or src/auth/waSignIn.js, then: npm run build:wa-sign-in-fn\n'
    + '// deno-lint-ignore-file\n// @ts-nocheck: the inlined library is plain JavaScript, tested in node\n\n';
  return header + template.replace(PLACEHOLDER, `// ---- from ${LIB}, edit there ----\n${lib.trim()}\n// ---- end ----`);
};

if (process.argv[1] && process.argv[1].endsWith('build-wa-sign-in-fn.mjs')) {
  mkdirSync(resolve(root, 'supabase/functions/wa-sign-in'), { recursive: true });
  writeFileSync(resolve(root, 'supabase/functions/wa-sign-in/index.ts'), buildWaSignInFn());
  console.log('wa-sign-in/index.ts written');
}

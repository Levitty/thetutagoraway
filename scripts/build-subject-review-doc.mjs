// ============================================================================
// THE REVIEW DOCUMENT for a subject-grade: what a teacher reads before signing families off. Free and local; every number
// comes from the files, nothing is typed by hand.
//   node scripts/build-subject-review-doc.mjs <subject> <grade>     writes docs/qa/<subject>-g<N>-review-<date>.md (never over an existing
//                                                                   pack such as science-g5-2026-11-12.md)
// Shows: the checks' verdict, each skill with its families and outcomes, the misconception library and which are revealed by a
// wrong answer, one drawn example per family with the feedback a child would read, and how to sign a family off.
// Maths Grade 5 and English keep their own packs (build-question-review.mjs, build-english-g5-doc.mjs, with routes).
// ============================================================================
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [subject, gradeArg] = process.argv.slice(2);
const grade = Number(gradeArg);
const { entryFor } = await import(resolve(root, 'src/ai-tutor/content/subjects/registry.js'));
const entry = entryFor(subject, grade);
if (!entry) { console.error(`no registry entry for ${subject} grade ${grade}: node scripts/new-subject.mjs first`); process.exit(1); }
const { drawFamily, setFamilyMode } = await import(resolve(root, 'src/ai-tutor/content/families/core.js'));
const DATE = new Date().toISOString().slice(0, 10);
const cell = (t) => String(t ?? '').replace(/\|/g, '/').replace(/\s+/g, ' ');

setFamilyMode('all');
let failures;
if (entry.checks === 'text') {
  const { checkEnglishFamily, checkTextForms } = await import(resolve(root, 'engine/scripts/english_checks.mjs'));
  failures = [...checkTextForms(entry.families, entry.map.skills), ...entry.families.flatMap(f => checkEnglishFamily(f, 150))];
} else {
  const { checkFamily } = await import(resolve(root, 'engine/scripts/family_checks.mjs'));
  failures = entry.families.flatMap(f => checkFamily(f));
}
const { skills, outcomes } = entry.map;
const lib = entry.misconceptionsFile && existsSync(resolve(root, entry.misconceptionsFile)) ? JSON.parse(readFileSync(resolve(root, entry.misconceptionsFile), 'utf8')) : null;
const revealed = new Set();
const example = new Map();
for (const f of entry.families) {
  for (let i = 0; i < 60; i++) {
    const { p } = drawFamily(f);
    for (const m of [...(p.misconceptions || []), ...[].concat(p.mis || []).map(x => ({ mis: x }))]) for (const c of [].concat(m.mis || [])) revealed.add(`${f.cskill}|${c}`);
    if (i === 0) example.set(f.id, p);
  }
}
setFamilyMode('reviewed');

const out = [], P = (s = '') => out.push(s);
P(`# ${entry.name}, Grade ${grade}: review pack (${DATE})`);
P();
P(`Generated by \`node scripts/build-subject-review-doc.mjs ${subject} ${grade}\`. Free and local; no model was called. **${entry.families.length} families**, ${Object.keys(skills).length} skills, ${Object.keys(outcomes).length} official outcomes. Every family is a **draft, off for children**, until you sign it off.`);
P();
P(`## Checks: ${failures.length ? `${failures.length} failure(s)` : 'all pass'}`);
P();
for (const f of failures.slice(0, 40)) P(`- ${cell(f)}`);
if (failures.length > 40) P(`- ... and ${failures.length - 40} more`);
P();
P('## Skills and their families');
P();
P('| Skill | Outcomes | Families | Forms | Misconceptions in the library | Revealed by a wrong answer |');
P('|---|---|---|---|---|---|');
for (const [code, k] of Object.entries(skills)) {
  const fams = entry.families.filter(f => f.cskill === code);
  const got = k.mis.filter(c => revealed.has(`${code}|${c}`)).length;
  P(`| ${code.replace(`${entry.prefix}.G${grade}.`, '')} | ${k.outcomes.map(o => o.split('.').pop()).join(', ')} | ${fams.length} | ${[...new Set(fams.map(f => f.form))].join(', ') || '.'} | ${k.mis.length} | ${got} |`);
}
P();
if (lib) {
  P('## Misconception library (draft)');
  P();
  P('| Code | The mistake | What a child is told | Revealed |');
  P('|---|---|---|---|');
  for (const [full, m] of Object.entries(lib)) P(`| ${full.replace(`${entry.prefix}.G${grade}.`, '')} | ${cell(m.error).slice(0, 110)} | ${cell(m.feedback).slice(0, 140)} | ${revealed.has(`${m.skill}|${full.slice(m.skill.length + 1)}`) ? 'yes' : 'no'} |`);
  P();
}
P('## One drawn example per family');
P();
P('Read the question, the right answer and what a child is told after a wrong one. If a family is right and clear, its id goes in the signed list.');
P();
for (const f of entry.families) {
  const p = example.get(f.id);
  P(`### ${f.id}`);
  P();
  P(`Skill \`${f.cskill.replace(`${entry.prefix}.G${grade}.`, '')}\`, outcome \`${String(f.outcome).split('.').pop()}\`, form ${f.form}, rung ${f.rung}.`);
  P();
  if (p.passage?.text) P(`> ${cell(p.passage.title)}: ${cell(p.passage.text).slice(0, 400)}`);
  P(`**Q:** ${cell(p.question)}`);
  if (p.choices) P(`Options: ${p.choices.map((c, i) => `${p.optionTruth?.[i] ? '**' + cell(c) + '**' : cell(c)}`).join(' | ')}`);
  else if (p.shownSteps) P(`Steps: ${p.shownSteps.map((t, i) => `${p.workingTruth?.[i] === false ? '**' + cell(t) + '**' : cell(t)}`).join(' / ')}`);
  else P(`Answer: **${cell(p.answer)}**`);
  const wrong = (p.misconceptions || []).filter(m => m.feedback).slice(0, 2);
  for (const m of wrong) P(`- If a child answers "${cell(m.when)}": ${cell(m.feedback)}`);
  P();
}
P('## How to sign a family off');
P();
P(`Add its id to the list in \`src/ai-tutor/content/families/${entry.signedFile}\` (\`${entry.signedFile.replace('.js', '')}\`). That is the one switch: a family not in the list is never served to a child.`);
const target = resolve(root, `docs/qa/${subject}-g${grade}-review-${DATE}.md`);
writeFileSync(target, out.join('\n') + '\n');
console.log(`written ${target.replace(root + '/', '')}: ${entry.families.length} families, ${failures.length} check failures`);

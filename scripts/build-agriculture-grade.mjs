// ============================================================================
// AGRICULTURE, ONE GRADE TO THE GRADE 5 MATHS STANDARD (18 Nov 2026, HOREB_MAPPING_PLAN.md). The one command for Grades 4 to 9:
//   node scripts/build-agriculture-grade.mjs 5
// 1. the first pass (scripts/build-agriculture-g<n>.mjs; Grade 9 had outcomes only, so it starts empty);
// 2. the depth pass (scripts/data/agriculture-depth/g<n>.mjs through scripts/agriculture-depth.mjs and scripts/science-depth.mjs):
//    new skills for outcomes that had none, prerequisites reaching the grades below, four or more misconceptions per skill, the
//    rubric line for practical outcomes, and the teaching pack curriculum/agriculture/teaching/g<n>/*.json;
// 3. the in-app map (scripts/build-subject-map.mjs), the skills with no family yet
//    (src/ai-tutor/content/families/agriculture_g<n>_awaiting.js) and the SQL (supabase/migrations/20261126_agriculture_g<n>_...sql
//    by scripts/build-maths-sql-grade.mjs, copied to ~/Desktop/Tuta Workspace/HOREB_SQL_Agriculture_G<n>.sql). NOT RUN.
// Build the grades in order (4, 5, ... 9): a prerequisite may name a skill of a grade below.
// ============================================================================
import { readFileSync, writeFileSync, copyFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { applyAgricultureDepth } from './agriculture-depth.mjs';
import { relinkLowerOutcomes } from './lib/lower-grade.mjs';

const ROOT = new URL('..', import.meta.url).pathname;
const GRADE = Number(process.argv[2]);
if (![4, 5, 6, 7, 8, 9].includes(GRADE)) { console.error('usage: node scripts/build-agriculture-grade.mjs 4|5|6|7|8|9'); process.exit(1); }
const run = (args) => { const r = spawnSync('node', args, { stdio: 'inherit', cwd: ROOT }); if (r.status) process.exit(r.status); };
const TITLE = GRADE <= 6 ? 'Agriculture and Nutrition' : 'Agriculture';
const ENTRY = join(ROOT, `src/ai-tutor/content/subjects/agriculture_g${GRADE}.js`);

if (process.argv.includes('--awaiting')) {
  // Read in a fresh process, after the map is rebuilt. Grade 9 has no subject entry and no families yet.
  const map = await import(`../src/ai-tutor/content/curriculumMap.agriculture.g${GRADE}.js`);
  const used = new Set(existsSync(ENTRY) ? (await import(ENTRY)).default.families.map(f => f.cskill) : []);
  const list = Object.keys(map.SKILLS).filter(c => !used.has(c));
  writeFileSync(join(ROOT, `src/ai-tutor/content/families/agriculture_g${GRADE}_awaiting.js`),
    `// GENERATED by scripts/build-agriculture-grade.mjs ${GRADE}. Do not edit by hand.\n` +
    `// The Grade ${GRADE} Agriculture skills that have no question family yet (${list.length} of ${Object.keys(map.SKILLS).length}).\n` +
    `// The checks list them for the family writers instead of failing; a skill that gets a family must leave this list (rebuild).\n` +
    `export const AWAITING = ${JSON.stringify(list, null, 1)};\n`);
  console.log(`agriculture g${GRADE}: ${list.length} skills with no family yet`);
  process.exit(0);
}

const FILE = join(ROOT, `curriculum/agriculture/g${GRADE}.json`);
if (GRADE <= 8) run([`scripts/build-agriculture-g${GRADE}.mjs`]);
const g = JSON.parse(readFileSync(FILE, 'utf8'));
if (GRADE === 9) for (const s of g.sub_strands) { s.skills = []; s.misconceptions = []; }
const { SUBS } = await import(`./data/agriculture-depth/g${GRADE}.mjs`);
const r = applyAgricultureDepth(g, SUBS, { grade: GRADE });
// Grade 1-3 outcome prerequisites name the Grade 1-3 skill that carries them (19 Nov 2026, scripts/lib/lower-grade.mjs).
const relink = relinkLowerOutcomes(g, { root: ROOT, label: `Agriculture Grade ${GRADE}` });
console.log(`agriculture g${GRADE}: ${relink.moved} Grade 1-3 outcome prerequisites now name skills (${relink.merged} merged), ${relink.kept.length} kept as outcomes`);
const DEPTH = '; depth pass 18 Nov 2026 (a skill for every testable outcome, two or more prerequisites and four misconceptions per skill, practical outcomes marked by the teacher with the KICD rubric, teaching pack in curriculum/agriculture/teaching/g' + GRADE + ')';
g.status = (GRADE === 9 ? "outcomes from KICD's text, word for word; skills, prerequisites and misconceptions proposed (authored offline, 18 Nov 2026), awaiting an Agriculture teacher's review" : g.status.replace(/; depth pass 18 Nov 2026.*$/, '')) + DEPTH;
writeFileSync(FILE, JSON.stringify(g, null, 1) + '\n');
console.log(`agriculture g${GRADE}: ${g.totals.skills} skills, ${g.totals.prerequisites} prerequisites, ${g.totals.misconceptions} misconceptions; depth ${r.subs} of ${r.of} sub-strands (+${r.pre} prerequisites, +${r.mis} misconceptions, ${r.pack} teaching pack entries)`);

run(['scripts/build-subject-map.mjs', 'agriculture', String(GRADE), '--dir', 'agriculture', '--title', TITLE]);
run(['scripts/build-agriculture-grade.mjs', String(GRADE), '--awaiting']);
run(['scripts/build-maths-sql-grade.mjs', 'agriculture', String(GRADE)]);
const sql = join(ROOT, `supabase/migrations/20261126_agriculture_g${GRADE}_skills_misconceptions.sql`);
const ws = join(homedir(), 'Desktop/Tuta Workspace');
if (existsSync(ws)) { copyFileSync(sql, join(ws, `HOREB_SQL_Agriculture_G${GRADE}.sql`)); console.log(`copied to Tuta Workspace/HOREB_SQL_Agriculture_G${GRADE}.sql`); }

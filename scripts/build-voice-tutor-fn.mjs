// Builds supabase/functions/voice-tutor/index.ts, one self-contained file (esbuild bundles what it
// imports), the same way build-school-practice-fn.mjs builds the school functions. The decision lives in
// src/voice-tutor/*.js (tested); the template only wires it to Supabase and the Messages API.
// Run after changing any of them:  npm run build:voice-tutor-fn
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** The function's file as it should be. The test compares it with the file in the repository. */
export async function buildVoiceTutorFn() {
  const r = await build({
    entryPoints: [resolve(root, 'scripts/voice-tutor.template.ts')], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
    external: ['https://*'], write: false, legalComments: 'none', loader: { '.ts': 'ts', '.json': 'json' },
    define: { 'import.meta.env': 'undefined' },
  });
  return '// GENERATED by scripts/build-voice-tutor-fn.mjs, do not edit here.\n'
    + '// Edit scripts/voice-tutor.template.ts or src/voice-tutor/*.js, then run: npm run build:voice-tutor-fn\n// @ts-nocheck\n\n'
    + r.outputFiles[0].text;
}

if (process.argv[1] && process.argv[1].endsWith('build-voice-tutor-fn.mjs')) {
  mkdirSync(resolve(root, 'supabase/functions/voice-tutor'), { recursive: true });
  writeFileSync(resolve(root, 'supabase/functions/voice-tutor/index.ts'), await buildVoiceTutorFn());
  console.log('voice-tutor/index.ts written');
}

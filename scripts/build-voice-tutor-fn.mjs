// Builds the live tutor's edge functions, each one self-contained file (esbuild bundles what it imports),
// the same way build-school-practice-fn.mjs builds the school functions:
//   supabase/functions/voice-tutor/index.ts         one tutor turn (scripts/voice-tutor.template.ts)
//   supabase/functions/voice-tutor-token/index.ts   short-lived voice tokens (scripts/voice-tutor-token.template.ts)
// The decisions live in src/voice-tutor/*.js (tested); the templates only wire them to Supabase and the APIs.
// Run after changing any of them:  npm run build:voice-tutor-fn
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const VOICE_FNS = ['voice-tutor', 'voice-tutor-token'];

/** Each function's file as it should be: { name: text }. The tests compare them with the files in the repository. */
export async function buildVoiceTutorFns() {
  const out = {};
  for (const name of VOICE_FNS) out[name] = await buildOne(name);
  return out;
}
/** The tutor function alone (kept for the milestone 1 test). */
export const buildVoiceTutorFn = () => buildOne('voice-tutor');

async function buildOne(name) {
  const r = await build({
    entryPoints: [resolve(root, `scripts/${name}.template.ts`)], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
    external: ['https://*'], write: false, legalComments: 'none', loader: { '.ts': 'ts', '.json': 'json' },
    define: { 'import.meta.env': 'undefined' },
  });
  return '// GENERATED by scripts/build-voice-tutor-fn.mjs, do not edit here.\n'
    + `// Edit scripts/${name}.template.ts or src/voice-tutor/*.js, then run: npm run build:voice-tutor-fn\n// @ts-nocheck\n\n`
    + r.outputFiles[0].text;
}

if (process.argv[1] && process.argv[1].endsWith('build-voice-tutor-fn.mjs')) {
  for (const [name, text] of Object.entries(await buildVoiceTutorFns())) {
    mkdirSync(resolve(root, `supabase/functions/${name}`), { recursive: true });
    writeFileSync(resolve(root, `supabase/functions/${name}/index.ts`), text);
    console.log(`${name}/index.ts written (${Math.round(text.length / 1024)} KB)`);
  }
}

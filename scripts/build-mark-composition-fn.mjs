// Builds supabase/functions/mark-composition/index.ts from:
//   scripts/mark-composition.template.ts   the function
//   src/ai/safeguarding.js                 the screen (shared with the tests)
//
// The screen has ONE source of truth on purpose. A second, hand-copied list of
// patterns inside the edge function would drift from the one tests/safeguarding
// .test.mjs checks, and the copy that protects a child would be the untested
// one. Same approach as scripts/build-weekly-report-fn.mjs.
//
// Run after changing either file:  npm run build:marking-fn
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');

const lib = read('src/ai/safeguarding.js')
  .replace(/^export default .*$/m, '')
  .replace(/^export const /gm, 'const ');

const PLACEHOLDER = '/*__SAFEGUARDING_LIB__*/';
const template = read('scripts/mark-composition.template.ts');
if (!template.includes(PLACEHOLDER)) {
  throw new Error(`template is missing ${PLACEHOLDER}`);
}

// The function calls these; if an export is ever renamed, fail here rather
// than ship a function that throws on its first submission.
for (const needed of ['const screen =', 'const CHILD_HELPLINE =']) {
  if (!lib.includes(needed)) throw new Error(`safeguarding.js no longer defines: ${needed}`);
}

const out = template.replace(
  PLACEHOLDER,
  `// ---- from src/ai/safeguarding.js — edit there, then: npm run build:marking-fn ----\n${lib.trim()}\n// ---- end ----`,
);

const header = '// GENERATED by scripts/build-mark-composition-fn.mjs — do not edit here.\n' +
  '// Edit scripts/mark-composition.template.ts or src/ai/safeguarding.js,\n' +
  '// then run: npm run build:marking-fn\n\n';

mkdirSync(resolve(root, 'supabase/functions/mark-composition'), { recursive: true });
writeFileSync(resolve(root, 'supabase/functions/mark-composition/index.ts'), header + out);
console.log(`mark-composition/index.ts written (${lib.split('\n').length} lines of screen inlined)`);

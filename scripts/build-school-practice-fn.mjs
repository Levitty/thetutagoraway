// Builds supabase/functions/school-practice/index.ts from:
//   scripts/school-practice.template.ts   the function
//   src/school/schoolDoor.js              the signature, link-code and status rules (tested)
// One self-contained file, so it can be deployed with the CLI or pasted into the dashboard.
// Run after changing either:  npm run build:school-fn
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');

const lib = read('src/school/schoolDoor.js').replace(/^export const /gm, 'const ');
const out = read('scripts/school-practice.template.ts')
  .replace('/*__DOOR_LIB__*/', `// ---- from src/school/schoolDoor.js ----\n${lib.trim()}\n// ---- end ----`);

const header = '// GENERATED by scripts/build-school-practice-fn.mjs — do not edit here.\n' +
  '// Edit scripts/school-practice.template.ts or src/school/schoolDoor.js, then run: npm run build:school-fn\n\n';
mkdirSync(resolve(root, 'supabase/functions/school-practice'), { recursive: true });
writeFileSync(resolve(root, 'supabase/functions/school-practice/index.ts'), header + out);
console.log('school-practice/index.ts written');

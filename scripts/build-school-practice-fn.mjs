// Builds the two school edge functions, each one self-contained file (esbuild bundles what they import),
// so it can be deployed with the CLI or pasted into the dashboard:
//   supabase/functions/school-practice/index.ts   from scripts/school-practice.template.ts (Tuta's signed door:
//                                                  practice, and homework drawn from the curriculum families)
//   supabase/functions/school-homework/index.ts   from scripts/school-homework.template.ts (the child's phone,
//                                                  and the learner home's data)
// and the learner home's drawing for the page with no account (11 Nov 2026):
//   public/hw/home.js                             from src/school/learnerHomeView.js (the family app imports it directly)
// The rules live in src/school/schoolDoor.js, homework.js and homeworkDoor.js (tested). The family bank comes
// in whole, reviewed or not: which families a homework may draw is the teacher's approval, checked at set time.
// Run after changing any of them:  npm run build:school-fn
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SCHOOL_FNS = ['school-practice', 'school-homework'];

/** Each function's file as it should be: { name: text }. The test compares these with the files in the repository. */
export async function buildSchoolFns() {
  const out = {};
  for (const name of SCHOOL_FNS) {
    const r = await build({
      entryPoints: [resolve(root, `scripts/${name}.template.ts`)], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
      external: ['https://*'], write: false, legalComments: 'none', loader: { '.ts': 'ts' },
      define: { 'import.meta.env': 'undefined' },
    });
    out[name] = `// GENERATED by scripts/build-school-practice-fn.mjs — do not edit here.\n` +
      `// Edit scripts/${name}.template.ts or src/school/*.js, then run: npm run build:school-fn\n// @ts-nocheck\n\n` + r.outputFiles[0].text;
  }
  return out;
}

/** public/hw/home.js as it should be: window.HorebHome = { homeHtml, HOME_CSS }. */
export async function buildHomeJs() {
  const r = await build({
    entryPoints: [resolve(root, 'src/school/learnerHomeView.js')], bundle: true, format: 'iife', globalName: 'HorebHome', platform: 'browser',
    target: 'es2017', write: false, legalComments: 'none', minify: true,
  });
  return `/* GENERATED by scripts/build-school-practice-fn.mjs from src/school/learnerHomeView.js. Do not edit here. */\n` + r.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [name, text] of Object.entries(await buildSchoolFns())) {
    mkdirSync(resolve(root, `supabase/functions/${name}`), { recursive: true });
    writeFileSync(resolve(root, `supabase/functions/${name}/index.ts`), text);
    console.log(`${name}/index.ts written (${Math.round(text.length / 1024)} KB)`);
  }
  const home = await buildHomeJs();
  writeFileSync(resolve(root, 'public/hw/home.js'), home);
  console.log(`public/hw/home.js written (${Math.round(home.length / 1024)} KB)`);
}

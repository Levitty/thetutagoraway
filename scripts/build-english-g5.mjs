// ============================================================================
// ENGLISH GRADE 5: merge the authored skills and misconception library into the file HOREB owns
// (curriculum/english/g5.json), then write the in-app map the question families read.
//   node scripts/build-english-g5.mjs
// Idempotent: skills, prerequisites and misconceptions are rebuilt from scripts/data/english-g5-skills.mjs
// every run; the official outcomes and sub-strand text are never touched.
// Writes src/ai-tutor/content/curriculumMap.english.g5.js (light, read by the families and checks).
// All skills are 'proposed' and all misconceptions 'draft' until a Kenyan English teacher reviews them.
// ============================================================================
import { readFileSync, writeFileSync } from 'node:fs';
import { SKILLS, MIS, ALSO } from './data/english-g5-skills.mjs';

const path = new URL('../curriculum/english/g5.json', import.meta.url);
const g5 = JSON.parse(readFileSync(path, 'utf8'));
const g4 = JSON.parse(readFileSync(new URL('../curriculum/english/g4.json', import.meta.url), 'utf8'));
const G4_OUTCOMES = new Set(g4.sub_strands.flatMap(s => s.outcomes.map(o => o.code)));
const P = 'ENGL.G5.';

const subOf = (key) => {
  const hit = g5.sub_strands.filter(s => s.code.startsWith(`${P}${key}_`));
  if (hit.length !== 1) throw new Error(`sub-strand key ${key} matches ${hit.length}`);
  return hit[0];
};
const codeOf = (sub, id) => `${sub.code}.${id}`;
for (const s of g5.sub_strands) { s.skills = []; s.misconceptions = []; }

const byKey = new Map();   // 'GRAMMA.T1.DEMONSTRATIVES' -> full code
for (const k of SKILLS) byKey.set(`${k.sub}.${k.id}`, codeOf(subOf(k.sub), k.id));
const resolvePre = (r) => {
  if (byKey.has(r)) return { requires: byKey.get(r), kind: 'skill' };
  if (G4_OUTCOMES.has(r)) return { requires: r, kind: 'outcome' };
  throw new Error(`unknown prerequisite ${r}`);
};

let nPre = 0;
for (const k of SKILLS) {
  const sub = subOf(k.sub);
  const outcomes = k.outcomes.map(l => {
    const o = sub.outcomes.find(x => x.letter === l);
    if (!o) throw new Error(`${k.sub}.${k.id}: no outcome ${l}`);
    return o.code;
  });
  for (const ref of ALSO[`${k.sub}.${k.id}`] || []) {
    const [a, b, letter] = ref.split('.');
    const other = subOf(`${a}.${b}`), o = other.outcomes.find(x => x.letter === letter);
    if (!o) throw new Error(`${k.sub}.${k.id}: no outcome ${ref}`);
    outcomes.push(o.code);
  }
  const prerequisites = k.pre.map(r => ({ ...resolvePre(r), strength: 'essential', reason: 'Proposed: this skill builds on it. To confirm by a Kenyan English teacher.', status: 'proposed' }));
  nPre += prerequisites.length;
  sub.skills.push({ code: codeOf(sub, k.id), name: k.name, outcomes, mastery: k.mastery, question_forms: k.forms, thinking: k.thinking, horeb_skill_ids: [], prerequisites, status: 'proposed' });
}
for (const m of MIS) {
  const [subKey, ...rest] = m.skill.split('.');
  const key = `${subKey}.${rest[0]}`;
  const skillCode = byKey.get(m.skill);
  if (!skillCode) throw new Error(`misconception ${m.code}: unknown skill ${m.skill}`);
  const sub = g5.sub_strands.find(s => skillCode.startsWith(`${s.code}.`));
  const full = `${skillCode}.${m.code}`;
  if (sub.misconceptions.some(x => x.code === full)) throw new Error(`duplicate ${full}`);
  sub.misconceptions.push({ code: full, skill: skillCode, error: m.error, example: m.example, cause: m.cause, reveals: m.reveals, help: m.help, feedback: m.feedback, source: m.source, status: 'draft' });
}
const all = g5.sub_strands;
g5.totals = { ...g5.totals, skills: all.reduce((n, s) => n + s.skills.length, 0), prerequisites: nPre, misconceptions: all.reduce((n, s) => n + s.misconceptions.length, 0) };
g5.status = "outcomes from KICD's text, word for word; skills, prerequisites and misconceptions (12 Nov 2026) are proposed or draft, written offline by Claude, awaiting a Kenyan English teacher's review";
writeFileSync(path, JSON.stringify(g5, null, 1) + '\n');

// ---- the in-app map ----
const subs = {}, outcomes = {}, skills = {}, feedback = {};
for (const s of all) {
  subs[s.code] = { name: s.sub_strand, strand: s.strand, outcomes: s.outcomes.map(o => o.code) };
  for (const o of s.outcomes) outcomes[o.code] = { letter: o.letter, sub: s.code };
  for (const k of s.skills) skills[k.code] = { name: k.name, sub: s.code, outcomes: k.outcomes, pre: k.prerequisites.filter(p => p.kind === 'skill').map(p => p.requires), mis: [] };
  for (const m of s.misconceptions) { skills[m.skill].mis.push(m.code.slice(m.skill.length + 1)); (feedback[m.skill] ||= {})[m.code.slice(m.skill.length + 1)] = m.feedback; }
}
writeFileSync(new URL('../src/ai-tutor/content/curriculumMap.english.g5.js', import.meta.url), `// GENERATED by scripts/build-english-g5.mjs from curriculum/english/g5.json (KICD 2024 design). Do not edit by hand.
// Outcomes are official. Skills are proposed and misconceptions are draft, awaiting a Kenyan English teacher.
// A family carries \`cskill\` (a key of SKILLS_E5), \`outcome\` (its official outcome code) and names the misconception behind each wrong answer.
export const OUTCOMES_E5 = ${JSON.stringify(outcomes, null, 1)};
export const SUBSTRANDS_E5 = ${JSON.stringify(subs, null, 1)};
export const SKILLS_E5 = ${JSON.stringify(skills, null, 1)};
// What a child is told when a wrong answer reveals a misconception: skill code -> short code -> feedback.
export const MIS_FEEDBACK_E5 = ${JSON.stringify(feedback, null, 1)};
`);
console.log(`${SKILLS.length} skills, ${nPre} prerequisites, ${MIS.length} misconceptions over ${all.filter(s => s.skills.length).length} sub-strands`);

// ============================================================================
// PRE-REVIEW CHECKS FOR EVERY ITEM: free, local, deterministic.
//   npm run review:precheck                 writes docs/qa/precheck-<date>.md
//   node scripts/review-precheck.mjs --draws 60 --strict   (exit 1 on any hard fail)
// Every question family (Maths and Grade 5 Science) and every Maths Grade 1 to 9 generator skill is drawn
// several times and run through scripts/lib/item-precheck.mjs. The model pass of
// the blind reviewer (solve without the key) is NOT built or run here.
// Counts, ids and a short example only; no learner data.
// ============================================================================
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { precheckItem, CHECKS } from './lib/item-precheck.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const DRAWS = Number(args[args.indexOf('--draws') + 1]) || 30;
const STRICT = args.includes('--strict');
const ENGLISH = args.includes('--english');   // English Grade 5 families only (marked by answerCheckText.js); writes precheck-english-g5-<date>.md
const DATE = new Date().toISOString().slice(0, 10);

const { SKILLS } = await import(resolve(root, 'src/ai-tutor/knowledgeGraph.js'));
const { generateProblem, tidyProblem } = await import(resolve(root, 'src/ai-tutor/problemGenerators.js'));
const { FAMILIES } = await import(resolve(root, 'src/ai-tutor/content/families/index.js'));
const { drawFamily, setFamilyMode } = await import(resolve(root, 'src/ai-tutor/content/families/core.js'));
const { SKILL_TAGS } = await import(resolve(root, 'src/ai-tutor/curriculum/skillTags.js'));

setFamilyMode('all');
const warn = console.warn; console.warn = () => {};
// sources: id -> { grade, kind, draw() }
const sources = [];
if (ENGLISH) {
  const { ENGLISH_FAMILIES } = await import(resolve(root, 'src/ai-tutor/content/families/english.js'));
  for (const f of ENGLISH_FAMILIES) sources.push({ id: f.id, grade: 5, kind: 'family', skill: f.cskill, draw: () => drawFamily(f).p });
}
// A science family is its own row ("Science 5"): it is held to the same checks as a Grade 5 item, but is counted apart from Maths.
if (!ENGLISH) for (const f of FAMILIES) sources.push({ id: f.id, grade: SKILL_TAGS[f.skill]?.grade ?? SKILLS[f.skill]?.grade ?? 5, label: f.subject === 'science' ? 'Science 5' : undefined, kind: 'family', skill: f.skill, draw: () => tidyProblem(drawFamily(f).p, f.skill) });
if (!ENGLISH) for (const [id, s] of Object.entries(SKILLS)) if (s.grade <= 9) sources.push({ id, grade: s.grade, kind: 'generator', skill: id, draw: () => generateProblem(id, { noFamilies: true, level: ['abstract', 'pictorial', 'concrete'][Math.floor(Math.random() * 3)] }) });

const perGrade = {}, byCheck = {};
const worst = new Map();   // source id -> { hard, soft, examples }
let items = 0, itemsHard = 0, itemsSoft = 0, clean = 0;
for (const src of sources) {
  const g = (perGrade[src.label || src.grade] ||= { items: 0, hard: 0, soft: 0, clean: 0, kinds: { family: 0, generator: 0 }, checks: Object.fromEntries(CHECKS.map(c => [c, { hard: 0, soft: 0 }])) });
  for (let i = 0; i < DRAWS; i++) {
    let p; try { p = src.draw(); } catch (e) { p = null; }
    if (!p) continue;
    items++; g.items++; g.kinds[src.kind]++;
    const found = precheckItem(p, { grade: src.grade, family: src.kind === 'family' });
    const hard = found.filter(x => x.level === 'hard'), soft = found.filter(x => x.level === 'soft');
    for (const x of found) { g.checks[x.id][x.level]++; const k = `${x.id}: ${x.message.replace(/-?\d[\d,.]*/g, '#')}`; const b = (byCheck[k] ||= { id: x.id, level: x.level, n: 0, example: `${src.id}: ${String(p.question).replace(/\s+/g, ' ').slice(0, 90)}` }); b.n++; }
    if (hard.length) { itemsHard++; g.hard++; } else if (soft.length) { itemsSoft++; g.soft++; } else { clean++; g.clean++; }
    if (found.length) { const w = worst.get(src.id) || { src, hard: 0, soft: 0 }; w.hard += hard.length ? 1 : 0; w.soft += soft.length ? 1 : 0; worst.set(src.id, w); }
  }
}
console.warn = warn; setFamilyMode('reviewed');

const out = [], P = (s = '') => out.push(s);
P(`# Pre-review checks${ENGLISH ? ', English Grade 5' : ''} (${DATE})`);
P();
P(`Generated by \`npm run review:precheck\` (\`scripts/review-precheck.mjs\`, checks in \`scripts/lib/item-precheck.mjs\`). Free, local and deterministic: no model was called. This is the part of the blind reviewer that needs no model. **The model pass (solve each item without the key) is not built and was not run.**`);
P();
P(ENGLISH ? `Sources: ${sources.length} English Grade 5 question families (all draft, off for children), ${DRAWS} draws each: ${items} items. English answers are marked by answerCheckText.js, not the Maths marker.` : `Sources: ${FAMILIES.length} question families (all, signed off or not; ${FAMILIES.filter(f => f.subject === 'science').length} of them Grade 5 Science) and ${sources.length - FAMILIES.length} generator skills of Maths Grades 1 to 9, ${DRAWS} draws each: ${items} items.`);
P();
P('Checks: **key** (the key marks itself right, exactly one option is right, an arithmetic question computes to its key, a working has one false step); **distractors** (every wrong option carries feedback naming the mistake; Grade 5 families name a library code); **reading** (Flesch-Kincaid at most the grade plus two, no sentence over 30 words, short enough for a phone); **ambiguity** (broken text, two questions in one, vague words, double negatives, an amount with no unit); **units** (metric, shillings, believable ages, speeds, masses, temperatures and prices, British spelling).');
P();
P('Hard means the item must not reach a reviewer. Soft means a reviewer should look.');
P();
P(`## Result`);
P();
P(`- Items drawn: ${items}`);
P(`- Clean: ${clean} (${Math.round(100 * clean / items)} percent)`);
P(`- With a soft flag only: ${itemsSoft}`);
P(`- With a hard failure: ${itemsHard}`);
P();
P('## By grade');
P();
P('| Grade | Items | Clean | Soft only | Hard | key (hard/soft) | distractors | reading | ambiguity | units |');
P('|---|---|---|---|---|---|---|---|---|---|');
for (const [gr, g] of Object.entries(perGrade).sort((a, b) => (Number(a[0]) || 99) - (Number(b[0]) || 99))) P(`| ${gr} | ${g.items} | ${g.clean} | ${g.soft} | ${g.hard} | ${CHECKS.map(c => `${g.checks[c].hard}/${g.checks[c].soft}`).join(' | ')} |`);
P();
P('## Findings, commonest first');
P();
P('| Level | Check | Finding | Items | Example |');
P('|---|---|---|---|---|');
for (const [k, b] of Object.entries(byCheck).sort((a, b) => (a[1].level === 'hard' ? 0 : 1) - (b[1].level === 'hard' ? 0 : 1) || b[1].n - a[1].n).slice(0, 80)) P(`| ${b.level} | ${b.id} | ${k.slice(b.id.length + 2).replace(/\|/g, '/')} | ${b.n} | ${b.example.replace(/\|/g, '/')} |`);
P();
P('## Sources with a hard failure');
P();
const hardSources = [...worst.values()].filter(w => w.hard).sort((a, b) => b.hard - a.hard);
P(hardSources.length ? hardSources.slice(0, 100).map(w => `- ${w.src.id} (${w.src.kind}, Grade ${w.src.grade}): ${w.hard} of ${DRAWS} draws`).join('\n') : 'None.');
if (!args.includes('--no-write')) writeFileSync(resolve(root, `docs/qa/precheck-${ENGLISH ? 'english-g5-' : ''}${DATE}.md`), out.join('\n') + '\n');
console.log(`written docs/qa/precheck-${ENGLISH ? 'english-g5-' : ''}${DATE}.md: ${items} items, ${clean} clean, ${itemsSoft} soft only, ${itemsHard} hard`);
if (STRICT && itemsHard) process.exit(1);

// Builds supabase/functions/rocket-guide/index.ts from:
//   scripts/rocket-guide.template.ts   the wiring (Supabase, fetch)
//   src/rocket/{levels,guard,progress,guide,turn}.js   the decision, tested in node
//   src/ai/safeguarding.js             the safeguarding screen
//
// One source of truth, as with build-mark-composition-fn.mjs: the guard that
// stands between a model and a child is the guard tests/rocket-*.test.mjs run.
//
// Run after changing any of them:  npm run build:rocket-fn
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');

// Order matters: each file only uses what comes before it.
const FILES = ['src/rocket/levels.js', 'src/rocket/guard.js', 'src/rocket/progress.js', 'src/rocket/guide.js', 'src/rocket/turn.js', 'src/ai/safeguarding.js'];

const strip = (src, path) => {
  const out = src
    .replace(/^import [^\n]*;\n/gm, '')
    .replace(/^export default [^\n]*;\n?/gm, '')
    .replace(/^export (const|function|async function) /gm, '$1 ');
  if (/^\s*(import|export)\s/m.test(out)) throw new Error(`${path}: an import or export the build cannot inline (keep them on one line)`);
  return `// ---- from ${path}, edit there, then: npm run build:rocket-fn ----\n${out.trim()}\n`;
};

export const buildRocketFn = () => {
  const lib = FILES.map((p) => strip(read(p), p)).join('\n');
  for (const needed of ['async function runTurn(', 'const screen =', 'const CHILD_HELPLINE =', 'const DEFAULT_MODEL =']) {
    if (!lib.includes(needed)) throw new Error(`the inlined library no longer defines: ${needed}`);
  }
  // The files are inlined into one scope: two top-level names alike would make the function fail to start.
  const names = [...lib.matchAll(/^(?:const|let|var|function|async function|class) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
  const dup = names.filter((n, i) => names.indexOf(n) !== i);
  if (dup.length) throw new Error(`duplicate top-level names across the inlined files: ${[...new Set(dup)].join(', ')}`);
  const PLACEHOLDER = '/*__ROCKET_LIB__*/';
  const template = read('scripts/rocket-guide.template.ts');
  if (!template.includes(PLACEHOLDER)) throw new Error(`template is missing ${PLACEHOLDER}`);
  const header = '// GENERATED by scripts/build-rocket-guide-fn.mjs, do not edit here.\n'
    + '// Edit scripts/rocket-guide.template.ts or src/rocket/*.js, then: npm run build:rocket-fn\n'
    + '// deno-lint-ignore-file\n// @ts-nocheck: the inlined library is plain JavaScript, tested in node\n\n';
  return header + template.replace(PLACEHOLDER, `// ---- end of the wiring above; the inlined library follows ----\n${lib}// ---- end ----`);
};

if (process.argv[1] && process.argv[1].endsWith('build-rocket-guide-fn.mjs')) {
  mkdirSync(resolve(root, 'supabase/functions/rocket-guide'), { recursive: true });
  writeFileSync(resolve(root, 'supabase/functions/rocket-guide/index.ts'), buildRocketFn());
  console.log('rocket-guide/index.ts written');
}
